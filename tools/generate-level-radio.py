"""Radio messages of the level: data for the 68000 and own SVP drawing code.

Specification: build/research/radio-messages.md (USA rev0; tools/extract-radio.py
checks the ROM, the 29 code anchors and reproduces text and faces pixel by
pixel against BizHawk captures). Reused here: its ROM checks, table parser and
layout/face decoders.

68000 (build/level-radio.inc): message pointer table 01:FBB8 and data
01:E820 (person, sound, colour, text, 0), font translation 01:E6B6 (c-32) and
widths 01:D90A. The 68000 owns send_message_l 03:E993, friends_messages_l
03:E9EA and the line layout (mgetlinelen 01:B604 + print loop 01:B599).
SVP (build/svp-radio.inc, cmd8 types 6..8, drawn after the polygons as the
GSU kernels draw after the 3D frame, VR packed bitmap, x includes +16):
  type 6 SVP_RadioFace   x, y, src low WORD, PM ROM mode $0800|src>>16:
                         32x40 opaque copy (mcopyface 01:D15B copies whole
                         words, index 0 included); the faces live with the
                         68000 data (M4RadioFaces) and are read through the
                         PM ROM mode (outside the 128 KB program space)
  type 7 SVP_RadioGlyph  x, y, glyph, width, colour: 12 rows of the 1bpp
                         font 01:D996 (pixel i = bit 15-i), rows >= 192 not
                         drawn (msprintstr/mfprintstr PLOT, colour 0 skipped)
  type 8 SVP_RadioRect   x, y, w, h, colour (mshowteammate2 01:B7D1 box/bar)
Faces 17:B9C0 (18 frames, 4bpp planar 4 columns x 5 tiles) are converted to
40 rows x 8 packed WORDs (pixel x&3 at nibble 12-4*(x&3)) without changing
indices: the level palette line 2 is gamepal 3 (03:8B0A), as on the SNES.
"""
import hashlib
import json
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = runpy.run_path(str(ROOT / 'tools/extract-radio.py'), run_name='radio')
rom = R['ROM_PATH'].read_bytes()
assert len(rom) == 1048576 and hashlib.sha256(rom).hexdigest() == R['SHA'] and rom[0x7FDB] == 0
for bank, addr, hx, what in R['ANCHORS']:
    assert rom[R['phys'](bank, addr):R['phys'](bank, addr) + len(hx) // 2].hex() == hx, what
phys = R['phys']
radio = R['Radio'](rom)
tp = phys(*R['MSG_TABLE'])
ptrs = [rom[tp + 2 * i] | rom[tp + 2 * i + 1] << 8 for i in range(R['MSG_COUNT'])]
start = phys(0x01, ptrs[0])
end = phys(*R['MSG_TABLE'])
data = rom[start:end]
assert len(data) == 5016 and data[-1] == 0

out = ['; Generated by tools/generate-level-radio.py (USA rev0 01:FBB8, 01:E820, 01:E6B6, 01:D90A).',
       f'M4_RADIO_MESSAGES equ {len(ptrs)}', 'M4RadioMsgPtr:']
for i in range(0, len(ptrs), 16):
    out.append('        dc.w ' + ','.join(str(phys(0x01, p) - start) for p in ptrs[i:i + 16]))
out.append('M4RadioMsgData:')
for i in range(0, len(data), 32):
    out.append('        dc.b ' + ','.join(f'${b:02x}' for b in data[i:i + 32]))
out.append('M4RadioTrn: ;character c (32..127) -> glyph t = trn[c-32]')
trn = [radio.trn[c] for c in range(32, 128)]
for i in range(0, 96, 32):
    out.append('        dc.b ' + ','.join(str(t) for t in trn[i:i + 32]))
out.append('M4RadioWidth: ;glyph t -> pixels drawn and advance')
glyphs = R['GLYPHS']
for i in range(0, glyphs, 35):
    out.append('        dc.b ' + ','.join(str(radio.wid[t]) for t in range(i, min(glyphs, i + 35))))
out.append('        even')
out.append('M4RadioFaces: ;18 frames x 40 rows x 8 packed WORDs (SVP PM ROM reads)')
for f in range(R['FACE_FRAMES']):
    for row in radio.face_pixels(f):
        out.append('        dc.w ' + ','.join(f'${row[4 * k] << 12 | row[4 * k + 1] << 8 | row[4 * k + 2] << 4 | row[4 * k + 3]:04x}'
                                         for k in range(8)))
(ROOT / 'build/level-radio.inc').write_text('\n'.join(out) + '\n', encoding='ascii')

# ---------------------------------------------------------------- SVP code
lines = ['; Generated by tools/generate-level-radio.py: own SVP radio box drawing (cmd8 types 6..8).']


def emit(*words):
    lines.append('        dc.w ' + ','.join(f'${w & 65535:04x}' if isinstance(w, int) else w for w in words))


def label(name): lines.append(name + ':')
def load(slot): emit(0xe003, 0x0600 + slot)
def store(slot): emit(0x0e00 + slot)
def imm(value): emit(0xe003, 0x0830, value)
def call(name): emit(0x4800, name + '/2')
def ret(): emit(0x0065)
def readrom(): emit(0x4a10, 0xe003, 0x0031)
def branch(name, cond='always'):
    emit({'always': 0x4c00, 'z1': 0x4d50, 'z0': 0x4c50, 'n1': 0x4d70, 'n0': 0x4c70}[cond], name + '/2')
def add(slot): emit(0x8600 + slot)
def sub(slot): emit(0x2600 + slot)
def addi(v): emit(0x8800, v)
def subi(v): emit(0x2800, v)
def cmpi(v): emit(0x6800, v)
def andi(v): emit(0xa800, v)
def shl(n): emit(*([0x9003] * n))
def sar(n): emit(*([0x9002] * n))
def pm_read(slot): load(slot); emit(0x00e3, 0x08e0, 0x0818, 0x000c); emit(0xe003, 0x003c)
def pm_write(addr, value): load(addr); emit(0x00e3, 0x08e0, 0x0818, 0x00c0); load(value); emit(0x00c3)


# RAM1 work slots (after the sprite slots 0x1a0..0x1cb; cmd8 uses RAM0 only).
(RX, RY, RC, RADDR, RNIB, RVAL, RTMP, RROW, RBITS, RCNT, RSRC, RW, RH, RX0, RPAR, RREM) = range(0x1d0, 0x1e0)


def address(xs, ys):
    """RADDR = base + (y>>4)*1024 + (x>>3)*32 + (y&15)*2 + ((x&7)>>2) (as SVP_GridPlot)."""
    load(ys); sar(4); andi(0x0fff); shl(10); store(RADDR)
    load(ys); andi(15); shl(1); add(RADDR); store(RADDR)
    load(xs); sar(3); andi(0x1fff); shl(5); add(RADDR); store(RADDR)
    load(xs); andi(4); sar(2); add(RADDR); add(0xf6); store(RADDR)


label('SVP_RadioFace')   # 0x41 x (multiple of 8), 0x42 y, 0x43 source WORD low, 0x44 PM ROM mode
imm(0); store(RROW); load(0x43); store(RSRC); load(0x44); store(RW); load(0x41); store(RX)
label('SVP_RadFaceRow')
load(0x42); add(RROW); store(RY)
address(RX, RY)
imm(4); store(RCNT)
label('SVP_RadFaceCol')
for k in range(2):
    load(RSRC); emit(0x00e3); load(RW); emit(0x00e3, 0x000c); emit(0xe003, 0x003c); store(RVAL)  # PM ROM read
    pm_write(RADDR, RVAL)
    load(RSRC); addi(1); store(RSRC); branch(f'SVP_RadFaceNoCarry{k}', 'z0')
    load(RW); addi(1); store(RW)                                   # next 64K-WORD ROM bank
    label(f'SVP_RadFaceNoCarry{k}')
    load(RADDR); addi(1); store(RADDR)
load(RADDR); addi(30); store(RADDR)
load(RCNT); subi(1); store(RCNT); branch('SVP_RadFaceCol', 'z0')
load(RROW); addi(1); store(RROW); cmpi(40); branch('SVP_RadFaceRow', 'z0')
ret()

# Span writer: up to 16 pixels of one row from RX (bitmap x), RBITS bit 15 =
# first pixel, RCNT pixels, colour RC. The WORD address is computed once;
# the pixels of each 4-pixel WORD are merged and written with one DRAM write
# in overwrite mode (PMC $0C18: zero nibbles keep the underlying pixels, as
# the GSU PLOT leaves colour 0 unwritten).
label('SVP_RadSpan')
address(RX, RY)
load(RX); andi(3); store(RNIB)
load(RX); andi(4); store(RPAR)
imm(0); store(RVAL)
label('SVP_RadSpanPix')
load(RBITS); cmpi(0); branch('SVP_RadSpanNoPix', 'n0')
load(RNIB); shl(4); add(RC); addi('SVP_SprNibVals/2'); readrom(); emit(0xc600 + RVAL); store(RVAL)
label('SVP_RadSpanNoPix')
load(RBITS); shl(1); store(RBITS)
load(RCNT); subi(1); store(RCNT)
load(RNIB); addi(1); store(RNIB); cmpi(4); branch('SVP_RadSpanWord', 'z1')
load(RCNT); cmpi(0); branch('SVP_RadSpanLast', 'z1')
load(RBITS); cmpi(0); branch('SVP_RadSpanLast', 'z1')
branch('SVP_RadSpanPix')
label('SVP_RadSpanWord')
load(RVAL); cmpi(0); branch('SVP_RadSpanAdvance', 'z1')
load(RADDR); emit(0x00e3, 0x08e0, 0x0c18, 0x00c0); load(RVAL); emit(0x00c3)
label('SVP_RadSpanAdvance')
load(RPAR); cmpi(0); branch('SVP_RadSpanOdd', 'z0')
load(RADDR); addi(1); store(RADDR); imm(4); store(RPAR); branch('SVP_RadSpanNext')
label('SVP_RadSpanOdd'); load(RADDR); addi(31); store(RADDR); imm(0); store(RPAR)
label('SVP_RadSpanNext')
imm(0); store(RNIB); store(RVAL)
load(RCNT); cmpi(0); branch('SVP_RadRet', 'z1')
load(RBITS); cmpi(0); branch('SVP_RadRet', 'z1')
branch('SVP_RadSpanPix')
label('SVP_RadSpanLast')
load(RVAL); cmpi(0); branch('SVP_RadRet', 'z1')
load(RADDR); emit(0x00e3, 0x08e0, 0x0c18, 0x00c0); load(RVAL); emit(0x00c3)
ret()

label('SVP_RadioGlyph')  # 0x41 x, 0x42 y, 0x43 glyph rows WORD address, 0x44 width, 0x45 colour
load(0x45); store(RC); imm(0); store(RROW)
label('SVP_RadGlyphRow')
load(0x42); add(RROW); store(RY)
imm(191); sub(RY); branch('SVP_RadRet', 'n1')             # rows >= 192 are not drawn
load(0x43); add(RROW); readrom(); store(RBITS)
cmpi(0); branch('SVP_RadGlyphNext', 'z1')
load(0x41); store(RX); load(0x44); store(RCNT)
cmpi(0); branch('SVP_RadGlyphNext', 'z1')
call('SVP_RadSpan')
label('SVP_RadGlyphNext')
load(RROW); addi(1); store(RROW); cmpi(12); branch('SVP_RadGlyphRow', 'z0')
label('SVP_RadRet'); ret()

label('SVP_RadioRect')   # 0x41 x, 0x42 y, 0x43 w, 0x44 h, 0x45 colour: 16-pixel spans
load(0x45); store(RC); load(0x42); store(RY); load(0x44); store(RH)
label('SVP_RadRectRow')
load(RH); cmpi(0); branch('SVP_RadRet', 'z1')
load(0x41); store(RX0); load(0x43); store(RREM)
label('SVP_RadRectSpan')
load(RREM); cmpi(0); branch('SVP_RadRectNext', 'z1')
load(RX0); store(RX); imm(0xffff); store(RBITS)
load(RREM); store(RCNT); imm(16); sub(RREM); branch('SVP_RadRectFull', 'n0')
imm(16); store(RCNT)
label('SVP_RadRectFull')
load(RREM); sub(RCNT); store(RREM)
call('SVP_RadSpan')
load(RX0); addi(16); store(RX0); branch('SVP_RadRectSpan')
label('SVP_RadRectNext')
load(RY); addi(1); store(RY); load(RH); subi(1); store(RH); branch('SVP_RadRectRow')

label('SVP_RadioGlyphs')  # 140 x 12 row WORDs
for t in range(glyphs):
    rows = radio.glyph(t)
    emit(*[sum(bit << (15 - i) for i, bit in enumerate(r)) for r in rows])
(ROOT / 'build/svp-radio.inc').write_text('\n'.join(lines) + '\n', encoding='ascii')
(ROOT / 'build/level-radio.json').write_text(json.dumps(dict(
    rom_sha256=R['SHA'], messages=len(ptrs), message_bytes=len(data),
    message_data_sha256=hashlib.sha256(data).hexdigest(), glyphs=glyphs, face_frames=R['FACE_FRAMES'],
    faces_sha256=hashlib.sha256(rom[phys(*R['FACE_BASE']):phys(*R['FACE_BASE']) + 640 * R['FACE_FRAMES']]).hexdigest()),
    indent=1) + '\n')
print('Generated radio data:', len(ptrs), 'messages,', glyphs, 'glyphs,', R['FACE_FRAMES'], 'faces')
