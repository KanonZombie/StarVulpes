"""Own SVP port of the GSU scaled text `msprint` 01:CEF0 loops (cmd8 type 13), USA rev0.

Authority: ref/Star Fox (USA).sfc (SHA-256 3857b529...a84d), GSU code 01:CFA0..D039 (small scale) and
01:D03E..D159 (`mlargescale`), re-read with build/research/gsu_dis.py; checked pixel by pixel against the
ROM's own msprint executed by the TextGSU of tools/recover-intro-font.py (tools/check-ending-text.py).

The 68000 (src/stages/level_ending.asm M4EndTextFace) runs the projection part of msprint (01:CEF0..CF9F,
mprojectpnt 01:9263, divisions 01:8183 / 01:9493) and passes the state at the start of the Y loop as one raw
cmd8 record (face kind 34):
  0x40 type 13
  0x41 x  = m_bigx after centring (GSU screen x, signed)    0x42 y = m_bigy after centring
  0x43 scale = r8 = r9 (rxscale/ryscale)                    0x44 colour (GSU colour 1..15, plotted as is)
  0x45 string: byte index of its first code in SVP_STextStr (14:C8DA..CDEC packed two codes per WORD, high
       byte first; the 68000 rejects pointers outside it)
  0x46 sprsize = m_sprsize ($B6, 8 bits after `lob`)       0x47 0 small path, 1 large path
Derived here: clipleft $A0 = 0 (small) / -sprsize (large), clipright $A2 = 224 - sprsize.

Loops (GSU delay slots resolved; r1 x, r2 y, r4 source row, r6/r7 Y/X accumulators, r8/r9 scale):
  small (CFA7): rows y in 0..191 drawn; per char: x <= 0 -> x += sprsize (whole char skipped);
    x > clipright - 2 -> row ends; 16 source columns: r7 -= r9; on borrow the column is emitted (plot at x when
    its bit is set), x += 1. Row step (D01B): r6 -= r8; borrow -> y += 1 and next source row drawn, else the
    source row is skipped. 16 source rows.
  large (D060): per char: x <= -sprsize -> x += sprsize and one X step (+1 without borrow, D12F);
    x < 0 -> partial clip loop (D0B6): each source column advances x by the number of subtractions up to the
    borrow, nothing plotted; after a SET column x >= 0 switches to the normal loop (D0CC);
    x > clipright - 1 -> right clip (D103): as normal but the row ends at x >= 223 and after the char;
    normal (D0EA): a set column plots one pixel per subtraction up to the borrow (x += 1 each).
    Row step (D13F): y += 1; r6 -= r8; borrow -> next source row. 16 source rows.
Unsigned borrow without SSP carry: as tools/generate-svp-text.py (signs of the operands).
Pixel write: VR packed bitmap as SVP_GridPlot / SVP_RadioGlyph (word = base + (y>>4)*1024 + ((x+16)>>3)*32 +
(y&15)*2 + (((x+16)&7)>>2), nibble (x+16)&3), one DRAM write in overwrite mode (PMC $0C18) per pixel; pixels
outside x 0..223 or y 0..191 are not written (the GSU screen is 224 x 192).

Glyphs: codes 1..26 (A..Z) read SVP_TextFont of tools/generate-svp-text.py (the same 26 glyphs of the
ROM font, checked here); codes 27..65 go through SVP_STextGlyphMap to the distinct remaining glyphs
(SVP_STextFontX). Only the release (M4_STEXT) assembles this unit: the code in the SSP program window after
SVP_SphFastEnd, reached through SVP_STextDispatch (types 11 and 13 of cmd8, size-neutral in
tools/generate-intro-raster.py); the glyph map, glyphs and strings in the 68000 ROM data next to the
graphics117 window, read through PM4 (the program window is the scarce space).

Output: build/svp-ending-text.inc (SSP code, SVP_STextDispatch..SVP_STextEnd) and
build/svp-ending-text-rom.inc (SVP_STextData..SVP_STextDataEnd, one 64K-WORD page).
Usage: python tools/generate-svp-ending-text.py (extract_sf.ps1, after tools/extract-ending-font.py)
"""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROM = (ROOT / 'ref/Star Fox (USA).sfc').read_bytes()
assert hashlib.sha256(ROM).hexdigest() == '3857b5294ea8f7468849437bb2d8271564e8a0ff30774622e9c872bcbd53a84d'
FONT = (ROOT / 'build/agent-ending/ending-font.bin').read_bytes()      # tools/extract-ending-font.py
assert len(FONT) == 65 * 32 and FONT == ROM[0xA3EDA:0xA3EDA + 65 * 32]
STR_FIRST, STR_END = 0xC8DA, 0xCDEC                                     # 14:C8DA..CDEC (0xA48DA..0xA4DEC)
STRINGS = ROM[0xA48DA:0xA4DEC]
assert max(STRINGS) <= 65

INTRO_FONT = (ROOT / 'build/intro-text-font.bin').read_bytes()      # tools/recover-intro-font.py
assert INTRO_FONT == FONT[:26 * 32], 'codes 1..26 must equal SVP_TextFont'
lines = ['; Generated by tools/generate-svp-ending-text.py: own SVP port of msprint 01:CFA0..D159 (cmd8 type 13).']


def emit(*words):
    lines.append('        dc.w ' + ','.join(f'${w & 65535:04x}' if isinstance(w, int) else w for w in words))


def label(name): lines.append(name + ':')
def load(slot): emit(0xe003, 0x0600 + slot)
def store(slot): emit(0x0e00 + slot)
def imm(value): emit(0xe003, 0x0830, value)
def call(name): emit(0x4800, name + '/2')
def ret(): emit(0x0065)
def readrom(): emit(0x4a10, 0xe003, 0x0031)
def readpm(base):
    """a = WORD at base + a (68000 ROM, PM4 read; the table stays inside one 64K-WORD page)."""
    emit(0x8800, f'(({base}/2)&$ffff)')
    emit(0x00e3, 0x08e0, f'$0800|(({base}/2)>>16)', 0x000c, 0xe003, 0x003c)
def branch(name, cond='always'):
    emit({'always': 0x4c00, 'z1': 0x4d50, 'z0': 0x4c50, 'n1': 0x4d70, 'n0': 0x4c70}[cond], name + '/2')
def add(slot): emit(0x8600 + slot)
def sub(slot): emit(0x2600 + slot)
def xor(slot): emit(0xe600 + slot)
def addi(v): emit(0x8800, v)
def subi(v): emit(0x2800, v)
def cmpi(v): emit(0x6800, v)
def andi(v): emit(0xa800, v)
def shl(n): emit(*([0x9003] * n))
def sar(n): emit(*([0x9002] * n))
def inc(slot): load(slot); addi(1); store(slot)


# RAM1 work slots (temporaries of one cmd8 primitive; the sprite range 0x1a0.. is reused).
(X, Y, ROW, YACC, XACC, STR, BITS, CNT, TMP, CLIPL, CLIPR, SCALE, COL, SPR, ADDR, PIX) = range(0x1a0, 0x1b0)
_n = [0]


def acc_step(acc, borrowed, no_borrow):
    """acc -= SCALE (16 bits); branch on the unsigned borrow (GSU sub carry clear)."""
    _n[0] += 1
    t = 'SVP_STextAcc%d' % _n[0]
    load(acc); store(TMP); sub(SCALE); store(acc)
    load(TMP); xor(SCALE); andi(0x8000); branch(t, 'z1')
    load(TMP); andi(0x8000); branch(borrowed, 'z1'); branch(no_borrow)
    label(t)
    load(acc); cmpi(0); branch(borrowed, 'n1'); branch(no_borrow)


def next_bit():
    """PIX = bit 15 of BITS (the GSU rol carry), BITS <<= 1."""
    load(BITS); andi(0x8000); store(PIX)
    load(BITS); shl(1); store(BITS)


def fetch_char(end):
    """GSU getb / add r0 / beq: next code of the string, 0 ends the row; BITS = font row ROW of it.
    STR is a byte index into SVP_STextStr (two codes per WORD, high byte first)."""
    _n[0] += 1
    odd, got, ext, done = ('SVP_STextC%d%s' % (_n[0], s) for s in ('Odd', 'Got', 'Ext', 'Done'))
    load(STR); sar(1); andi(0x7fff); readpm('SVP_STextStr'); store(TMP)
    load(STR); andi(1); branch(odd, 'z0')
    load(TMP); sar(8); andi(0xff); store(TMP); branch(got)
    label(odd)
    load(TMP); andi(0xff); store(TMP)
    label(got)
    inc(STR)
    load(TMP); cmpi(0); branch(end, 'z1')
    cmpi(27); branch(ext, 'n0')                               # codes 1..26: the intro font
    load(TMP); subi(1); shl(4); add(ROW); addi('SVP_TextFont/2'); readrom(); store(BITS); branch(done)
    label(ext)                                                # codes 27..65: glyph slot * 16
    load(TMP); subi(27); readpm('SVP_STextGlyphMap'); add(ROW); readpm('SVP_STextFontX'); store(BITS)
    label(done)


# cmd8 types 11 and 13 (the type-11 test of the primitive dispatch branches here, size-neutral).
label('SVP_STextDispatch')
load(0x40); cmpi(11); branch('SVP_IntroTexPoly', 'z1')
load(0x40); cmpi(13); branch('SVP_STextPrim', 'z1')
branch('SVP_IntroPrimRest')
label('SVP_STextPrim')                                     # as SVP_IntroSprite: call, next primitive
call('SVP_SText'); branch('SVP_IntroNextPrimitive')

label('SVP_SText')
load(0x44); store(COL); load(0x43); store(SCALE); load(0x46); andi(0xff); store(SPR)
imm(224); sub(SPR); store(CLIPR)
imm(0); sub(SPR); store(CLIPL)
load(0x42); store(Y); imm(0); store(YACC); store(ROW)
load(0x47); cmpi(0); branch('SVP_STextLarge', 'z0')

# ---------------------------------------------------------------- small path 01:CFA7
label('SVP_STextSRow')
load(Y); cmpi(0); branch('SVP_STextSStep', 'n1')
cmpi(192); branch('SVP_STextSStep', 'n0')
load(0x41); store(X); imm(0); store(XACC); load(0x45); store(STR)
label('SVP_STextSChar')
fetch_char('SVP_STextSStep')
load(X); cmpi(1); branch('SVP_STextSDraw', 'n0')          # 0 - x < 0: x > 0
load(X); add(SPR); store(X); branch('SVP_STextSChar')     # whole char skipped (CFE9)
label('SVP_STextSDraw')
load(CLIPR); subi(2); sub(X); branch('SVP_STextSStep', 'n1')
imm(16); store(CNT)
label('SVP_STextSPix')
next_bit()
acc_step(XACC, 'SVP_STextSEmit', 'SVP_STextSNext')
label('SVP_STextSEmit')
load(PIX); cmpi(0); branch('SVP_STextSAdv', 'z1')
call('SVP_STextPlot')
label('SVP_STextSAdv')
inc(X)
label('SVP_STextSNext')
load(CNT); subi(1); store(CNT); branch('SVP_STextSPix', 'z0')
branch('SVP_STextSChar')
label('SVP_STextSStep')                                    # D01B
acc_step(YACC, 'SVP_STextSDown', 'SVP_STextSSkip')
label('SVP_STextSSkip')
inc(ROW); cmpi(16); branch('SVP_STextSStep', 'z0'); ret()
label('SVP_STextSDown')
inc(Y); inc(ROW); cmpi(16); branch('SVP_STextSRow', 'z0'); ret()

# ---------------------------------------------------------------- large path 01:D060
label('SVP_STextLarge')
label('SVP_STextLRow')
load(Y); cmpi(0); branch('SVP_STextLStep', 'n1')
cmpi(192); branch('SVP_STextLStep', 'n0')
load(0x41); store(X); imm(0); store(XACC); load(0x45); store(STR)
label('SVP_STextLChar')                                    # D07D
fetch_char('SVP_STextLStep')
load(CLIPL); sub(X); branch('SVP_STextLIn', 'n1')         # clipleft - x < 0
load(X); add(SPR); store(X)                               # D12F absleftclip
acc_step(XACC, 'SVP_STextLChar', 'SVP_STextLAbsInc')
label('SVP_STextLAbsInc')
inc(X); branch('SVP_STextLChar')
label('SVP_STextLIn')
load(X); cmpi(0); branch('SVP_STextLNorm', 'n0')          # D0AA: x >= 0
imm(16); store(CNT)
label('SVP_STextLClip')                                    # D0B6
next_bit()
label('SVP_STextLClipRun')                                 # D0BA / D0C4: sub, x += 1 until the borrow
acc_step(XACC, 'SVP_STextLClipEnd', 'SVP_STextLClipMore')
label('SVP_STextLClipMore')
inc(X); branch('SVP_STextLClipRun')
label('SVP_STextLClipEnd')
inc(X)
load(PIX); cmpi(0); branch('SVP_STextLClipCnt', 'z1')
load(X); cmpi(0); branch('SVP_STextLClipCnt', 'n1')        # D0C9 bmi: still left of 0
load(CNT); subi(1); store(CNT); branch('SVP_STextLNPix', 'z0')  # D0CC: switch to the normal loop
branch('SVP_STextLChar')
label('SVP_STextLClipCnt')
load(CNT); subi(1); store(CNT); branch('SVP_STextLClip', 'z0')
branch('SVP_STextLChar')
label('SVP_STextLNorm')                                    # D0D9
load(CLIPR); subi(1); sub(X); branch('SVP_STextLRight', 'n1')
imm(16); store(CNT)
label('SVP_STextLNPix')                                    # D0EA
next_bit()
load(PIX); cmpi(0); branch('SVP_STextLNSet', 'z0')
label('SVP_STextLNBlank')                                  # D0EE
acc_step(XACC, 'SVP_STextLNBlankEnd', 'SVP_STextLNBlankMore')
label('SVP_STextLNBlankMore')
inc(X); branch('SVP_STextLNBlank')
label('SVP_STextLNBlankEnd')
inc(X); branch('SVP_STextLNCnt')
label('SVP_STextLNSet')                                    # D0F8: sub, plot (x += 1) until the borrow
acc_step(XACC, 'SVP_STextLNSetEnd', 'SVP_STextLNSetMore')
label('SVP_STextLNSetMore')
call('SVP_STextPlot'); inc(X); branch('SVP_STextLNSet')
label('SVP_STextLNSetEnd')
call('SVP_STextPlot'); inc(X)
label('SVP_STextLNCnt')
load(CNT); subi(1); store(CNT); branch('SVP_STextLNPix', 'z0')
branch('SVP_STextLChar')
label('SVP_STextLRight')                                   # D103
imm(16); store(CNT)
label('SVP_STextLRPix')                                    # D10C
next_bit()
load(PIX); cmpi(0); branch('SVP_STextLRSet', 'z0')
label('SVP_STextLRBlank')                                  # D110
acc_step(XACC, 'SVP_STextLRBlankEnd', 'SVP_STextLRBlankMore')
label('SVP_STextLRBlankMore')
inc(X); branch('SVP_STextLRBlank')
label('SVP_STextLRBlankEnd')
inc(X)
load(X); cmpi(223); branch('SVP_STextLStep', 'n0')        # D115: x >= 223 ends the row
branch('SVP_STextLRCnt')
label('SVP_STextLRSet')                                    # D120: x >= 223 ends; sub; plot
load(X); cmpi(223); branch('SVP_STextLStep', 'n0')
acc_step(XACC, 'SVP_STextLRSetEnd', 'SVP_STextLRSetMore')
label('SVP_STextLRSetMore')
call('SVP_STextPlot'); inc(X); branch('SVP_STextLRSet')
label('SVP_STextLRSetEnd')
call('SVP_STextPlot'); inc(X)
label('SVP_STextLRCnt')
load(CNT); subi(1); store(CNT); branch('SVP_STextLRPix', 'z0')
label('SVP_STextLStep')                                    # D13F (also after a right-clipped char)
inc(Y)
acc_step(YACC, 'SVP_STextLDown', 'SVP_STextLRow')
label('SVP_STextLDown')
inc(ROW); cmpi(16); branch('SVP_STextLRow', 'z0'); ret()

# ---------------------------------------------------------------- pixel (GSU plot, colour COL)
label('SVP_STextPlot')
load(X); cmpi(0); branch('SVP_STextPlotRet', 'n1')
cmpi(224); branch('SVP_STextPlotRet', 'n0')
load(Y); cmpi(0); branch('SVP_STextPlotRet', 'n1')
cmpi(192); branch('SVP_STextPlotRet', 'n0')
load(Y); sar(4); andi(0x0fff); shl(10); store(ADDR)
load(Y); andi(15); shl(1); add(ADDR); store(ADDR)
load(X); addi(16); sar(3); andi(0x1fff); shl(5); add(ADDR); store(ADDR)
load(X); addi(16); andi(4); sar(2); add(ADDR); add(0xf6); store(ADDR)
load(X); addi(16); andi(3); shl(4); add(COL); addi('SVP_SprNibVals/2'); readrom(); store(TMP)
load(ADDR); emit(0x00e3, 0x08e0, 0x0c18, 0x00c0); load(TMP); emit(0x00c3)
label('SVP_STextPlotRet')
ret()

# Glyphs of codes 27..65 (font index code - 1), each distinct one once (tools/extract-ending-font.py).
glyphs, slots = [], []
for code in range(27, 66):
    g = FONT[(code - 1) * 32:code * 32]
    if g not in glyphs:
        glyphs.append(g)
    slots.append(glyphs.index(g) * 16)
label('SVP_STextEnd')
code_lines, lines = lines, ['; Generated by tools/generate-svp-ending-text.py: msprint glyphs and strings (68000 ROM, PM4).',
                            '        even', 'SVP_STextData:']
label('SVP_STextGlyphMap')  # code 27..65 -> WORD offset of its glyph in SVP_STextFontX
emit(*slots)
label('SVP_STextFontX')
for g in glyphs:
    emit(*[g[2 * r] | g[2 * r + 1] << 8 for r in range(16)])
label('SVP_STextStr')       # 14:C8DA..CDEC, two codes per WORD, high byte first (0 ends a string)
packed = STRINGS + bytes(len(STRINGS) & 1)
for i in range(0, len(packed), 32):
    emit(*[packed[j] << 8 | packed[j + 1] for j in range(i, min(i + 32, len(packed)), 2)])
label('SVP_STextDataEnd')
lines += ['        if ((SVP_STextDataEnd-1)>>17)<>(SVP_STextData>>17)',
          '        inform 3,"msprint data crosses a 64K-WORD page"', '        endif']
lines.append(f'SVP_STEXT_STR_FIRST equ ${STR_FIRST:04x}')
lines.append(f'SVP_STEXT_STR_END equ ${STR_END:04x}')
for name, body in (('svp-ending-text.inc', code_lines), ('svp-ending-text-rom.inc', lines)):
    out = ROOT / 'build' / name
    out.write_text('\n'.join(body) + '\n', encoding='ascii')
    print('Generated', out.relative_to(ROOT), len(body), 'lines')
