def escape_formation():
    rows = []
    for entry in (0xd59e, 0xd61e, 0xd69e):
        data = code(6, entry, entry + 0x80)
        mate = operand(data, rb'\xad([\xa2-\xa4]\x18)') - 0x18a1
        dx, dy, dz = [add_to_y(data, field) for field in (0x0c, 0x0e, 0x10)]
        rotation = immediate_store(data, b'\x99\x26\x00', 2)
        delay = immediate_store(data, b'\x99\x22\x00')
        rows.append((mate, dx, dy, rotation, dz, delay))
    emit('m4-venom-escape-formation', rows, 'wwwwww', '06:D59E/D61E/D69E (mate, dx, dy, turn, dz, delay)')


def missile_pods():
    rows, labels = [], []
    for label, entry in [('M4VoMpX', 0xe80d), ('M4VoMpH', 0xe75a), ('M4VoMpV', 0xe6a7)]:
        data = code(8, entry, entry + 0xb3)
        # Persistent offset and angle writes between calls to fire_weapon.
        shots = re.split(rb'\x22\x46\xd1\x1f', data)
        assert len(shots) == 6
        stores = (b'\x8d\x47\x15', b'\x8d\x49\x15', b'\x8d\x4b\x15', b'\x95\x12', b'\x95\x13')
        state = [None] * len(stores)
        for index, shot in enumerate(shots[:-1]):
            for field, store in enumerate(stores):
                values = re.findall(rb'\xa9(.)' + re.escape(store), shot, re.S)
                if values:
                    state[field] = values[-1][0]
            assert all(value is not None for value in state)
            rows.append(tuple(state))
            labels.append(label if index == 0 else None)
    emit('m4-venom-missile-pods', rows, 'bbbbb', '08:E80D/E75A/E6A7 (dx, dy, dz, rx, ry)', labels=labels)


def weapons():
    # Destination type order. The original fire_weapon doubles each entry
    # index (even command IDs); $3A and $3C call the base missile routines.
    ids = (0x0a, 0x0c, 0x26, 0x06, 0x38, 0x12, 0x02, 0x04, 0x08, 0x0e, 0x14, 0x16,
           0x18, 0x1a, 0x1c, 0x20, 0x24, 0x2e, 0x30, 0x32, 0x3a, 0x3c, 0x3e)
    dispatch = code(0x1f, 0xd17c, 0xd17c + 32 * 6)
    routines = {i: int.from_bytes(dispatch[i*3:i*3+3], 'little') for i in range(0, 64, 2)}
    entries = sorted({site & 0xffff for site in routines.values() if site >> 16 == 6})
    ends = dict(zip(entries, entries[1:] + [0xb53c], strict=True))
    constants, sounds = [], []
    for index, command in enumerate(ids):
        site = routines[command]
        assert site >> 16 == 6
        start = site & 0xffff
        body = code(6, start, ends[start])
        if command in (0x3a, 0x3c):
            base = operand(body, rb'^\x22(..)\x06')
            body = code(6, base, ends[base])
        hp = immediate_store(body, b'\x99\x2a\x00')
        ap = immediate_store(body, b'\x99\x2b\x00')
        life = immediate_store(body, b'\x99\x0a\x00')
        # $FF selects doelaserspeed in the port. STB sets speed in its Istrat.
        speed_default = 0xff if b'\x20\x3c\xb5' in body else 0 if command == 0x1a else None
        speed = immediate_store(body, b'\x99\x15\x00', default=speed_default)
        flags = 0
        for mask in re.findall(rb'\xb9\x2e\x00\x09(.)\x99\x2e\x00', body, re.S):
            flags |= mask[0]
        zadd = operand(body, rb'\xad\x4b\x15\x18\x69(..)\x8d\x4b\x15', signed=True, default=0)
        values = (hp, ap, speed, life, flags, zadd)
        assert all(-128 <= value <= 255 for value in values)
        constants.extend((f'M4WpCfg{index:02d}{name}', value)
                         for name, value in zip(('HP', 'AP', 'Speed', 'Life', 'Coll', 'Z'), values, strict=True))
        helpers = [int.from_bytes(target, 'little') for target in re.findall(rb'\x22(..)\x03', body, re.S)
                   if 0xb66d <= int.from_bytes(target, 'little') <= 0xb6ed]
        assert len(helpers) <= 1
        sound = 0  # A weapon without a sound-helper call stays silent.
        if helpers:
            helper = code(3, helpers[0], helpers[0] + 24)
            loads = re.findall(rb'\xa9(.)((?:\x8d[\x4a-\x4e]\x1f)+)', helper, re.S)
            sound, = [value[0] for value, stores in loads if b'\x8d\x4b\x1f' in stores]
        sounds.append(sound)
    emit('m4-weapon-parameters', [], '', '1F:D17C and bank 06 (port type order)', constants=constants)
    emit('m4-weapon-sounds', [sounds], 'b' * len(ids), '1F:D17C -> bank 06 -> 03:B66D..B702 (csnd)')


def direct_tables():
    # File name, LoROM bank and address, element count and width.
    tables = [('m4-depth-tunnel', 0x03, 0x8fae, 4, 1),
              ('m4-depth-normal', 0x03, 0x8faa, 4, 1),
              ('m4-depth-offset1', 0x03, 0x8f9a, 4, 1),
              ('m4-depth-stage1', 0x03, 0x8fb6, 4, 1),
              ('m4-meteor-leg-y', 0x00, 0xeead, 4, 2),
              ('m4-pm-warp-shapes', 0x0b, 0x8b90, 4, 2),
              ('m4-pm-clear-shapes', 0x06, 0x80fd, 4, 2),
              ('m4-orbital-warp-shapes', 0x0a, 0xc66f, 4, 2)]
    for name, bank, address, count, width in tables:
        data = code(bank, address, address + count * width)
        values = [int.from_bytes(data[i:i+width], 'little') for i in range(0, len(data), width)]
        emit(name, [values], ('b' if width == 1 else 'w') * count, f'{bank:02X}:{address:04X}')

    petals = macbeth_petals()
    emit('m4-macbeth-petal-models', [petals], 'www', '08:9793', constants=[('M4MbPetalInitial', petals[0])])

    command, position = title_demo()
    emit('m4-title-demo-command', [command], 'bbbbbb', '0D:FA18 (map command and spawn)',
         constants=zip(('M4TitleDemoX', 'M4TitleDemoY', 'M4TitleDemoZ'), position, strict=True))


