def explosion_classes():
    limits = [operand(code(6, at, at + 3), rb'^\xc9(..)') for at in (0xf57c, 0xf584, 0xf58c)]
    subtractions = [operand(code(6, at, at + 3), rb'^\xe9(..)') for at in (0xf663, 0xf615, 0xf5c6)]
    assert subtractions == limits
    shifts = []
    for at in (0xf67a, 0xf62c, 0xf5dd):
        instructions = code(6, at, at + 8)
        shifts.append(len(instructions) - len(instructions.lstrip(b'\x4a')))
    assert all(shifts)
    counts = immediate_stores(code(6, 0xf598, 0xf687), b'\x99\x0b\x00')[::-1]
    constants = []
    for name, values in (('Ticks', counts), ('Shift', shifts), ('Limit', limits)):
        constants.extend((f'M4Ex{name}{i}', value) for i, value in enumerate(values, 1))
    assert len(counts) == 4
    emit('m4-explosion-classes', [], '', '06:F57C..F686 (smallest class first)', constants=constants)


def route_parameters():
    constants = [(f'M4RouteStart{i}', value) for i, value in enumerate(route_defaults())]
    for name, entry, expected_index in (('Change1', 0xd0c2, 0), ('Change2', 0xd0d1, 1),
                                        ('BlackHole1', 0xd0e7, 3), ('BlackHole2', 0xd0f2, 3),
                                        ('BlackHole3', 0xd0fd, 3)):
        index, value = route_write(entry + 3)
        assert index == expected_index
        constants.append((f'M4Route{name}', value))
    emit('m4-route-parameters', [], '', '03:BDA8..BDBF and 03:D0C2..D108', constants=constants)


