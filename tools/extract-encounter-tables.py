    emit('m4-armada-tunnel-enter', rows[:3], FLIGHT_LIMIT_LAYOUT, '0B:C044/C116/C1E8',
         labels=['M4PmLimSTunnel', 'M4PmLimMTunnel', 'M4PmLimLTunnel'])
    emit('m4-armada-tunnel-exit', rows[3:], FLIGHT_LIMIT_LAYOUT, '0B:C39E/C474',
         labels=['M4PmLimMTexit', 'M4PmLimLTexit'])


