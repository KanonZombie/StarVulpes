    data = code(0x06, 0xeadf, 0xeb9e)
    factories = {0xeefd: 0, 0xeeee: 1, 0xeedf: 2}
    calls = re.findall(rb'\x22(..)\x06\x22\x67\xef\x06\xa9(.)\x99\x0a\x00', data, re.S)
