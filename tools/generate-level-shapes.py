"""68000 records of the level shape catalog (tools/level-shapes.py).

Per shape: original BSP nodes (op, visibility, group, left, right), face
groups (count, visibility, material, eight byte-offset indices, normal: the
28-byte records of intro_mesh.asm) and a descriptor
  dc.l BSP, Groups, Colours ; dc.w nodes, SVP model, header CPU address, flags
Box and draw data come from the same ROM header (+10 xmax, +12 ymax, +14 zmax).
"""
import hashlib
import json
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rom = (ROOT / 'ref/Star Fox (USA).sfc').read_bytes()
assert hashlib.sha256(rom).hexdigest() == '3857b5294ea8f7468849437bb2d8271564e8a0ff30774622e9c872bcbd53a84d'
LEVEL = runpy.run_path(str(ROOT / 'tools/level-shapes.py'))
entries = LEVEL['catalog'](rom)
lines = ['; Generated by tools/generate-level-shapes.py from the selected USA rev0 ROM.',
         f'M4_LEVEL_SHAPES equ {len(entries)}']
report = []
shared_faces = {}
for e in entries:
    m, prefix = e['model'], 'M4LevelShape' + str(e['index'])
    nodes = m['bsp'] or [dict(op=68, group=0)]  # direct Faces group: implicit order
    key = repr(([[n.get(k, -1) for k in ('op', 'visibility', 'group', 'left', 'right')] for n in nodes],
                [[[f.get(k) for k in ('count', 'visibility', 'material', 'vertices', 'normal')]
                  for f in g['faces']] for g in m['groups']]))
    canonical = shared_faces.setdefault(key, prefix)
    record_start = len(lines)
    lines.append(prefix + 'BSP:')
    for node in nodes:
        lines.append('        dc.w ' + ','.join(str(node.get(k, -1)) for k in ('op', 'visibility', 'group', 'left', 'right')))
    lines.append(prefix + 'Groups:')
    lines += [f'        dc.l {prefix}Group{i}' for i in range(len(m['groups']))]
    faces = 0
    for i, group in enumerate(m['groups']):
        lines += [f'{prefix}Group{i}:', f'        dc.w {len(group["faces"])}']
        for face in group['faces']:
            assert 2 <= face['count'] <= 8
            values = [face['count'], face['visibility'], face['material'],
                      *(v * 6 for v in face['vertices']), *([0] * (8 - face['count'])),
                      *face.get('normal', [0, 0, 0])]
            lines.append('        dc.w ' + ','.join(map(str, values)))
            faces += 1
    if canonical != prefix:
        lines[record_start:] = [f'{prefix}BSP equ {canonical}BSP', f'{prefix}Groups equ {canonical}Groups']
    h = rom[e['header'] - 0x8000:e['header'] - 0x8000 + 28]
    word = lambda o: int.from_bytes(h[o:o + 2], 'little')
    e['box'] = dict(xmax=word(10), ymax=word(12), zmax=word(14), size=word(16),
                    sortz=int.from_bytes(h[5:7], 'little', signed=True))
    report.append(dict(index=e['index'], name=e['name'], header=f'00:{e["header"]:04X}', svp_model=e['svp_model'],
                       vertices=len(m['vertices']), faces=faces, nodes=len(nodes), **e['box']))
# Collision box lists: header+8 = WRAM 7E address of a 18-byte colbox chain
# copied from ROM 02:(addr+$4E6D) (same relation as the collision code).
# Port record: dc.w count, then per box xoff,yoff,zoff,rotflags,xmax,ymax,zmax,flagset.
# Animated lists (record +2 frames = n, e.g. boss_7_3/4 colframes 16): n
# consecutive single-box records, one per frame; the port stores -n and the
# collision code selects box (animframe & 15) (corneria-boss.md section 7).
# Mixed chains (base_0 E794): static boxes, then an animated record whose frame records have their own
# next pointers. 02:9E41..9E6E selects record base + 18 * k, k = (animframe if its bit 7 else
# gameframe) & (n - 1), and A102 follows THAT record's next. The port stores, per frame k, the flat list
# static boxes + record k + its chain: dc.w $4000+n, n WORD offsets (from the list label), n lists.
# The same layout serves any animated record whose frame count is not the legacy 16 (up_door D198: n = 10,
# mask n - 1 = 9 as in the ROM, so only frames 0/1/8/9 are ever selected) and chains whose next records are
# themselves animated with the same n (iris BDE8: 4 lists of 8 frames; 02:9E41 selects frame k again in each).
MIXED_ANIMATED_COLBOX = True


def colbox_at(addr):
    b = rom[0x10000 + ((addr + 0x4e6d) & 0x7fff):][:18]
    sv = lambda o: int.from_bytes(b[o:o + 2], 'little', signed=True)
    assert not b[9] & 0x80, 'rotxyz colbox not supported'
    return [sv(3), sv(5), sv(7), b[9], sv(10), sv(12), sv(14), b[16]], int.from_bytes(b[0:2], 'little')


for e in entries:
    h = rom[e['header'] - 0x8000:e['header'] - 0x8000 + 28]
    cb = int.from_bytes(h[8:10], 'little')
    e['boxes'], e['animated'], e['frames'] = [], 0, None
    while cb:
        b = rom[0x10000 + ((cb + 0x4e6d) & 0x7fff):][:18]
        sv = lambda o: int.from_bytes(b[o:o + 2], 'little', signed=True)
        nexts = [int.from_bytes(rom[0x10000 + ((cb + 18 * k + 0x4e6d) & 0x7fff):][:2], 'little')
                 for k in range(b[2])]
        if b[2] and (e['boxes'] or any(nexts) or b[2] != 16):
            n = b[2]   # 02:9E41: k = (animframe if bit 7 else gameframe) & (n - 1); M4LcFrameList does the same
            assert n <= 64, (e['name'], 'frame count')
            e['frames'] = []
            for k in range(n):
                box, nxt = colbox_at(cb + 18 * k)
                lst = e['boxes'] + [box]
                while nxt:
                    m = rom[0x10000 + ((nxt + 0x4e6d) & 0x7fff) + 2]
                    assert m in (0, n), (e['name'], 'nested animation with another frame count')
                    box, nxt = colbox_at(nxt + 18 * k if m else nxt)
                    lst.append(box)
                assert len(lst) <= 10, (e['name'], k)
                e['frames'].append(lst)
            break
        if b[2]:
            assert not e['boxes'] and b[2] == 16, (e['name'], 'animated colbox layout')
            base = 0x10000 + ((cb + 0x4e6d) & 0x7fff)
            for k in range(b[2]):
                r = rom[base + 18 * k:base + 18 * k + 18]
                assert int.from_bytes(r[0:2], 'little') == 0 and not r[9] & 0x80, (e['name'], k)
                rv = lambda o: int.from_bytes(r[o:o + 2], 'little', signed=True)
                e['boxes'].append([rv(3), rv(5), rv(7), r[9], rv(10), rv(12), rv(14), r[16]])
            e['animated'] = b[2]
            break
        assert not b[9] & 0x80, (e['name'], 'rotxyz colbox not supported')
        e['boxes'].append([sv(3), sv(5), sv(7), b[9], sv(10), sv(12), sv(14), b[16]])
        cb = int.from_bytes(b[0:2], 'little')
        assert len(e['boxes']) <= 10
    if e['frames']:
        label = f'M4LevelShape{e["index"]}Boxes'
        lines += [f'{label}:', f'        dc.w ${0x4000 + len(e["frames"]):04x}']
        lines += [f'        dc.w {label}F{k}-{label}' for k in range(len(e['frames']))]
        for k, lst in enumerate(e['frames']):
            lines += [f'{label}F{k}:', f'        dc.w {len(lst)}']
            lines += ['        dc.w ' + ','.join(str(v) for v in box) for box in lst]
        e['boxes'] = e['frames'][0]   # non-empty: the descriptor points at the list label
    elif e['boxes']:
        lines.append(f'M4LevelShape{e["index"]}Boxes:')
        lines.append(f'        dc.w {-len(e["boxes"]) if e["animated"] else len(e["boxes"])}')
        lines += ['        dc.w ' + ','.join(str(v) for v in box) for box in e['boxes']]
lines.append('M4LevelShapeDescriptors:')
drawn_descriptors = {}
for e in entries:
    prefix = 'M4LevelShape' + str(e['index'])
    start = len(lines)
    lines += [f'        dc.l {prefix}BSP,{prefix}Groups,M4ColoursLevel_{e["name"]}',
              f'        dc.w {len(e["model"]["bsp"]) or 1},{e["svp_model"]},${e["header"]:04x},{e["box"]["sortz"]}',
              f'        dc.w {e["box"]["xmax"]},{e["box"]["ymax"]},{e["box"]["zmax"]},{e["box"]["size"]}',
              f'        dc.l {("M4LevelShape%dBoxes" % e["index"]) if e["boxes"] else 0}']
    drawn_descriptors[e['header']] = (lines[start:], e['svp_model'])
# Effect/weapon shapes created by strategies: drawn through the intro effect
# models (SVP ids in tools/generate-intro-geometry.py; draw kind = id + 2) and
# described by their own ROM headers (sortz, extents, sh_size/sh_shift for the
# explode_Istrat class). svp -1: never drawn (mediumshape ACF5 placeholder).
EFFECTS = [('ELASER2', 0xb34d, 1), ('EXPL6', 0xbe04, 2), ('EXPLOSION2', 0xb11d, 3), ('SMOKE', 0xadd5, 4),
           ('EXPL8', 0xbe20, 10), ('EXPLOSION3', 0xb139, 11), ('FLASH64', 0xb075, 14), ('FLASH32', 0xb091, 15),
           ('FLASH16', 0xb0ad, 16), ('EXPL4', 0xb587, 18), ('EXPLOSION', 0xb101, 19), ('EXPLOSION4', 0xb155, 20),
           ('BALL', 0xaeed, 21), ('SPARK', 0xb2a5, -1), ('MEDIUM', 0xacf5, -1), ('SMALL', 0xad11, -1), ('LARGE', 0xacd9, -1),
           ('HUGE', 0xacbd, -1), ('NUKE', 0xaf41, 22), ('BOOST', 0xb219, 22),
           # Asteroid Belt sprites (stage-asteroid1.md section 4: same billboard
           # points 11:F0D4 as AF41): small asteroid AF5D (t1B), asteroid2 AF79
           # (t1F; t03 with break_meteor's coltab 03:857F), black hole B005 (t50).
           ('ASTEROID_S', 0xaf5d, 22), ('ASTEROID2', 0xaf79, 22), ('BLACKHOLE', 0xb005, 22),
           # Space pylon core 00:DD14 (09:F967): no geometry (never drawn) but
           # its header box (100, 100, 100) is the one the pylon collides with.
           ('PILON_CORE', 0xdd14, -1),
           # Enemy weapon sprites (build/agent-weapons/WEAPONS.md): ovalbeam B021
           # (06:ABCA/06:AAC4), ringlaser AD65 (06:AC4D), playerbeam B1FD (06:A848);
           # billboard points 11:F0D4 like AF41 (svp 22).
           ('OVALBEAM', 0xb021, 22), ('RINGLASER', 0xad65, 22), ('PBEAM', 0xb1fd, 22)]
# mssprite effects (tools/generate-svp-sprites.py SHAPES): the descriptor's
# first LONG is its texture entry M4SpriteH<header> (the SVP model only
# carries the shared billboard geometry: B219/AF41/AEED use the same points).
SPRITES = {0xb11d, 0xadd5, 0xb139, 0xb075, 0xb091, 0xb0ad, 0xb101, 0xb155, 0xaeed, 0xaf41, 0xb219,
           0xaf5d, 0xaf79, 0xb005, 0xb021, 0xad65, 0xb1fd}
EFFECT_COLBOXES = set()  # effect headers whose ROM colbox chain is emitted (stage modules opt in)
for _m in LEVEL['stage_modules']():  # tools/stages/*.py
    EFFECTS += list(_m.get('EFFECTS', []))
    SPRITES |= set(_m.get('SPRITE_HEADERS', ()))
    EFFECT_COLBOXES |= set(_m.get('EFFECT_COLBOXES', ())) | set(_m.get('COLBOX_EFFECTS', ()))
effect_boxes = []
lines.insert(2, f'M4_FX_FIRST equ {len(entries)}')
for i, (name, header, svp) in enumerate(EFFECTS):
    h = rom[header - 0x8000:header - 0x8000 + 28]
    word = lambda o: int.from_bytes(h[o:o + 2], 'little')
    lines.insert(2, f'M4_FX_{name} equ {len(entries) + i} ;00:{header:04X}')
    if svp == -1 and header in drawn_descriptors:
        descriptor, model = drawn_descriptors[header]
        lines += descriptor
        report.append(dict(effect=name, header=f'00:{header:04X}', svp_model=model,
                           alias_of_drawn_header=True))
        continue
    if header in SPRITES:  # level-sprites.inc exists only in VR builds
        lines += ['        if def(M4_VR_DMA)', f'        dc.l M4SpriteH{header:04X},0,0', '        else',
                  '        dc.l 0,0,0', '        endif']
    else:
        lines += ['        dc.l 0,0,0']
    boxes, cb = [], int.from_bytes(h[8:10], 'little') if header in EFFECT_COLBOXES else 0
    while cb:  # same chain as the shapes above; single-box records only
        b = rom[0x10000 + ((cb + 0x4e6d) & 0x7fff):][:18]
        sv = lambda o: int.from_bytes(b[o:o + 2], 'little', signed=True)
        assert not b[2] and not b[9] & 0x80, (name, 'colbox layout not supported for effects')
        boxes.append([sv(3), sv(5), sv(7), b[9], sv(10), sv(12), sv(14), b[16]])
        cb = int.from_bytes(b[0:2], 'little')
        assert len(boxes) <= 10
    if boxes:
        effect_boxes += [f'M4LevelEffect{i}Boxes:', f'        dc.w {len(boxes)}']
        effect_boxes += ['        dc.w ' + ','.join(str(v) for v in x) for x in boxes]
    lines += [
              f'        dc.w 0,{svp & 0xffff},${header:04x},{int.from_bytes(h[5:7], "little", signed=True)}',
              f'        dc.w {word(10)},{word(12)},{word(14)},{word(16)}',
              f'        dc.l {"M4LevelEffect%dBoxes" % i if boxes else 0}']
    report.append(dict(effect=name, header=f'00:{header:04X}', svp_model=svp, xmax=word(10), ymax=word(12),
                       zmax=word(14), size=word(16), shift=h[7]))
lines.insert(2, f'M4_LEVEL_DESCRIPTORS equ {len(entries) + len(EFFECTS)}')
lines += effect_boxes  # after the descriptor array (32-byte stride kept)
# sh_shift (header+7) per descriptor: explode_Istrat 06:F45F sprite tx class.
shifts = [rom[e['header'] - 0x8000 + 7] for e in entries] + [rom[h - 0x8000 + 7] for _, h, _ in EFFECTS]
lines.append('M4LevelShapeShift:')
lines += ['        dc.b ' + ','.join(map(str, shifts[i:i + 16])) for i in range(0, len(shifts), 16)]
lines.append('        even')
for e in entries:
    lines.insert(2, f'M4_SH_{e["name"].upper()} equ {e["index"]}')
(ROOT / 'build/level-shapes.inc').write_text('\n'.join(lines) + '\n', encoding='ascii')
# Colour tables continue M4MeshColourTables (mesh kinds 23+index).
assert all(e['svp_model'] == 23 + e['index'] for e in entries)
(ROOT / 'build/level-shape-colours.inc').write_text(''.join(
    f'        dc.l M4ColoursLevel_{e["name"]}\n' for e in entries), encoding='ascii')
# Level polygon palette: gamepal blue loads CGRAM row 7 from 03:8B0A
# (tools/extract-corneria-background.py finding); same >>2 convention as
# build/intro-scene-palette.md.bin (03:8ACA).
pal = rom[0x18b0a:0x18b2a]
md = []
for i in range(16):
    c = int.from_bytes(pal[i * 2:i * 2 + 2], 'little')
    r, g, b = c & 31, (c >> 5) & 31, (c >> 10) & 31
    md.append(((b >> 2) << 9) | ((g >> 2) << 5) | ((r >> 2) << 1))
# sin16 table 00:99E5 (257 Q15 WORDs, sin[64]=32767): getview R() (GSU 01:829F).
sin16 = rom[0x19e5:0x19e5 + 514]
assert int.from_bytes(sin16[128:130], 'little') == 32767 and int.from_bytes(sin16[2:4], 'little') == 804
(ROOT / 'build/level-sin16.bin').write_bytes(b''.join(sin16[i:i + 2][::-1] for i in range(0, 514, 2)))
(ROOT / 'build/level-scene-palette.md.bin').write_bytes(b''.join(v.to_bytes(2, 'big') for v in md))
(ROOT / 'build/level-shapes.json').write_text(json.dumps(dict(
    rom_sha256=hashlib.sha256(rom).hexdigest(), descriptor_bytes=32, shapes=report), indent=1) + '\n')
print(f'Generated {len(entries)} level shapes, {sum(r.get("faces", 0) for r in report)} faces')
