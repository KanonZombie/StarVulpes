"""Own SSP translation of the GSU star field (dotsflag $FF, Asteroid Belt).

Original units (ref/Star Fox (USA).sfc, SHA-256 3857b529...a84d, rev0):
  minitdust 01:A861 (called by initmario3d 03:B85B <- initgame3d_l): m_rand 70:0140 = $19F8,
            120 stars x (x,y,z) from mrand starting at $19F8 (carry chain of ADC).
  mshowdust 01:A8A6..AAD8: per image, cube test around viewpos (+-$800, z +-$A00), view
            z<0 -> respawn (3 x mrand, asr6/asr6/lsr5+$200, M.r + viewpos), rel.W,
            ztab 14:896C projection, colour 14:BC6C/14:BCAC/3, double plot if z < $400.
Research: build/research/stage-asteroid1.md 1.4, build/research/work/spaceA/stars_check.py,
build/agent-stars/INTEGRATION.md (contract, deliberate differences).

DRAM contract (VR build, word addresses = (byte - $300000) / 2):
  M4_GEO_STARS  $301C40: 14 WORDs written by the 68000 per image (SVP idle):
      +0 m_dotsorstars ($16FB word; negative = stars, else nothing is done)
      +1 70:1A26 (low byte: 0 -> 14:BC6C, 1 -> 14:BCAC, other -> colour 3)
      +2..4 viewpos 70:00C6/C8/CA, +5..13 W = $161D..$162D = 70:00D2..E2 (row-major m11..m33)
  M4_STARS_STATE $31F600: SVP-owned: +0 magic $5344 (anything else -> minitdust first),
      +1 m_rand 70:0140, +2..361 the 120 stars (x,y,z) of 70:0B52.
Pixels: GSU (x, y) -> bitmap (x+16, y) of the sealed bank RAM0[$F6] (packed VR tile words),
row 192 of the second pixel is outside the 256x192 bitmap and is not written (port clip).

Usage: python -I tools/generate-svp-stars.py  -> build/agent-stars/svp-stars.inc, svp-stars.json
"""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'build' / 'agent-stars'
ROM_PATH = ROOT / 'ref' / 'Star Fox (USA).sfc'
ROM_SHA256 = '3857b5294ea8f7468849437bb2d8271564e8a0ff30774622e9c872bcbd53a84d'
INIT_CARRY = 0      # GSU CY at 01:A861: CY left by 01:8295 (03:B8C4), see INTEGRATION.md 3.2
MAGIC = 0x5344
COL0, COL1 = 0xA3C6C, 0xA3CAC   # 14:BC6C (4 x 16 bytes), 14:BCAC (16 bytes)

rom = ROM_PATH.read_bytes()
if hashlib.sha256(rom).hexdigest() != ROM_SHA256:
    raise SystemExit('unexpected ROM: ' + str(ROM_PATH))

lines = ['; Generated by tools/generate-svp-stars.py: GSU minitdust 01:A861 + mshowdust 01:A8A6 (stars).',
         '; Exported: SVP_Stars (call after the cmd8 clear), SVP_StarsSeed, SVP_StarPlot.',
         '; Uses SVP_RomReciprocal (ztab 14:896C, svp-rom-particles.inc), RAM1 $100..$12F,',
         '; RAM0 $30..$32 (plot arguments), RAM0 $F6 (bank), $1F0/$1F1 (vanishing offset), PM4, X, Y.']


def emit(*v): lines.append('        dc.w ' + ','.join(f'${x & 65535:04x}' if isinstance(x, int) else x for x in v))
def label(n): lines.append(n + ':')
def ld(n): emit(0x0600 + n)              # A.h = ram[n], A.l kept
def load(n): emit(0xe003, 0x0600 + n)    # A = ram[n] << 16
def store(n): emit(0x0e00 + n)
def imm(v): emit(0xe003, 0x0830, v)
def branch(n, c='always'): emit(dict(always=0x4c00, z1=0x4d50, z0=0x4c50, n1=0x4d70, n0=0x4c70)[c], n + '/2')
def call(n): emit(0x4800, n + '/2')
def ret(): emit(0x0065)
def addi(k): emit(0x8800, k if isinstance(k, str) else k & 0xffff)
def subi(k): emit(0x2800, k)
def cmpi(k): emit(0x6800, k)
def andi(k): emit(0xa800, k)
def eori(k): emit(0xe800, k)
def addm(n): emit(0x8600 + n)
def subm(n): emit(0x2600 + n)
def andm(n): emit(0xa600 + n)
def orm(n): emit(0xc600 + n)
def asr(k=1): emit(*([0x9002] * k))
def shl(k=1): emit(*([0x9003] * k))
def readrom(): emit(0x4a10, 0xe003, 0x0031)     # A = program word [A.h]
def product(a, b): emit(0x0600 + a, 0x0013, 0x0600 + b, 0x0023, 0x0037)   # A32 = 2ab: A.h = fq(a,b)
def pm_read(p): load(p); emit(0x00e3, 0x08e0, 0x0818, 0x000c)
def pm_write(p): load(p); emit(0x00e3, 0x08e0, 0x0818, 0x00c0)
def rd(): emit(0x003c)    # A.h = next DRAM word
def wr(): emit(0x00c3)    # next DRAM word = A.h
def ztab(): emit(0x8800, '((SVP_RomReciprocal/2)&$ffff)', 0x00e3, 0x08e0, '$0800|((SVP_RomReciprocal/2)>>16)',
                 0x000c, 0xe003, 0x003c)


def dot(a, b, c, ma, mb, mc):
    """A.h = fq(a,ma) + fq(b,mb) + fq(c,mc), one floor per product (GSU FMULT+ROL), 16-bit wrap.
    The final ADD sets N from bit 15 of the sum (A.l only holds the low product bits)."""
    product(a, ma); store(ACC)
    product(b, mb); addm(ACC); store(ACC)
    product(c, mc); addm(ACC)


def carry(a, b, s):
    """A.h = $8000 if a + b (+ carry in) carried out of bit 15, else 0; N = that carry.
    Full-adder identity: cout = a15.b15 | (a15|b15).~s15 (s = the 16-bit sum)."""
    load(s); eori(0xffff); store(TMP)
    load(a); orm(b); andm(TMP); store(TMP)
    load(a); andm(b); orm(TMP); andi(0x8000)


# RAM1 slots (per-primitive scratch of the cmd8 primitives; SVP_Stars runs before them).
(VX, VY, VZ) = range(0x100, 0x103)
M = list(range(0x103, 0x10c))           # W row-major m11..m33 (70:00D2..E2)
(FLAG, MODE, CX, CY, CNT, PTR, SEED, MAGIC_IN, SX, SY, SZ, DX, DY, DZ, ZV, XV, YV, R1, R2, R3,
 T, U, W, TMP, C, C3, ZC, K, PX, PY, COLR, ACC, IDX, ADDR, MASK, SH, VAL, CNT2) = range(0x10c, 0x132)
assert CNT2 < 0x1a0      # 0x1A0.. are SVP_Sprite/SVP_Radio scratch (not needed here, kept clear)
STARS_IN = '((M4_GEO_STARS-$300000)/2)'
STATE = '((M4_STARS_STATE-$300000)/2)'

# ---- SVP_Stars: called by SVP_IntroRaster right after the cmd8 clear (behind every polygon).
label('SVP_Stars')
imm(STARS_IN); store(PTR); pm_read(PTR)
for slot in (FLAG, MODE, VX, VY, VZ, *M):
    rd(); store(slot)
load(FLAG); cmpi(0); branch('SVP_StarsOn', 'n1'); ret()          # m_dotsorstars bit 15 (03:BAE3)
label('SVP_StarsOn')
imm(STATE); store(PTR); pm_read(PTR); rd(); store(MAGIC_IN); rd(); store(SEED)
load(MAGIC_IN); cmpi(MAGIC); branch('SVP_StarsSeeded', 'z1')
call('SVP_StarsSeed')                                              # minitdust 01:A861 (stage init)
label('SVP_StarsSeeded')
imm(112); addm(0x1f0); store(CX)                                   # 70:0034 = vanishx (02:F3F0: 112)
imm(96); addm(0x1f1); store(CY)                                    # 70:0036 = vanishy (96)
imm(120); store(CNT)                                               # 70:0040 counter 120..1
imm(STATE + '+2'); store(PTR)
label('SVP_StarsStar')
pm_read(PTR); rd(); store(SX); rd(); store(SY); rd(); store(SZ)
label('SVP_StarsTest')                                             # 01:A8B9..A926
load(SX); subm(VX); store(DX); addi(0x800); andi(0xf000); branch('SVP_StarsRegen', 'z0')
load(SY); subm(VY); store(DY); addi(0x800); andi(0xf000); branch('SVP_StarsRegen', 'z0')
load(SZ); subm(VZ); store(DZ); addi(0xa00); andi(0xe000); branch('SVP_StarsRegen', 'z0')
load(DZ); addi(0xa00); cmpi(0x1400); branch('SVP_StarsInCube', 'n1'); branch('SVP_StarsRegen')
label('SVP_StarsInCube')
dot(DX, DY, DZ, M[2], M[5], M[8]); store(ZV); branch('SVP_StarsRegen', 'n1')   # zv < 0: respawn
dot(DX, DY, DZ, M[0], M[3], M[6]); store(XV)
dot(DX, DY, DZ, M[1], M[4], M[7]); store(YV)
# projection 01:AA2D..AAC2 (counter = CNT)
load(ZV); cmpi(0x3001); branch('SVP_StarsZ', 'n1'); imm(0x2fff)  # $3000 - z < 0 -> $2FFF
label('SVP_StarsZ'); store(ZC); cmpi(0x100); branch('SVP_StarsNext', 'n1')    # z < 256: skip
load(ZC); asr(); ztab(); store(K)                                  # ztab[z & ~1]
product(XV, K); addm(CX); store(PX); andi(0xff00); branch('SVP_StarsNext', 'z0')
load(PX); cmpi(224); branch('SVP_StarsNext', 'n0')                 # sx >= 224 (unsigned)
product(YV, K); addm(CY); store(PY); andi(0xff00); branch('SVP_StarsNext', 'z0')
load(PY); cmpi(192); branch('SVP_StarsNext', 'n0')                 # sy >= 192 (unsigned)
load(ZV); cmpi(0x1000); branch('SVP_StarsIdxZero', 'n0')           # hib(z) >= 16 -> 0
load(ZV); asr(8); andi(0xff); branch('SVP_StarsIdx')
label('SVP_StarsIdxZero'); imm(0)
label('SVP_StarsIdx'); store(IDX)
load(MODE); andi(0xff); branch('SVP_StarsMode0', 'z1'); cmpi(1); branch('SVP_StarsMode1', 'z1')
imm(3); branch('SVP_StarsColour')
label('SVP_StarsMode1'); load(IDX); addi('SVP_StarCol1/2'); readrom(); branch('SVP_StarsColour')
label('SVP_StarsMode0'); load(CNT); andi(3); shl(4); addm(IDX); addi('SVP_StarCol0/2'); readrom()
label('SVP_StarsColour'); andi(15); branch('SVP_StarsNext', 'z1'); store(0x32)  # colour 0: transparent
load(PX); addi(16); store(0x30); load(PY); store(0x31); call('SVP_StarPlot')
load(ZV); cmpi(0x400); branch('SVP_StarsNext', 'n0')               # z >= $400: one pixel
load(PY); cmpi(191); branch('SVP_StarsNext', 'z1')                 # port clip: row 192
load(PY); addi(1); store(0x31); call('SVP_StarPlot')               # PLOT advanced r1: (x, y+1)
label('SVP_StarsNext')
load(PTR); addi(3); store(PTR)
load(CNT); subi(1); store(CNT); branch('SVP_StarsStar', 'z0')
imm(STATE + '+1'); store(PTR); pm_write(PTR); load(SEED); wr()     # sms ($140)
ret()
label('SVP_StarsRegen'); call('SVP_StarsRespawn'); branch('SVP_StarsTest')

# ---- respawn 01:A96F..AA05: three mrand, r1 = asr6, r2 = asr6, r3 = lsr5 + $200; star = M.r + viewpos.
label('SVP_StarsRespawn')
imm(0x8000); store(C)                  # CY = 1: 'with r9; sub #6' never borrows
call('SVP_StarsRng'); load(SEED); asr(6); store(R1)
load(SEED); andi(0x20); shl(10); store(C)      # CY = bit shifted out by the 6th ASR
call('SVP_StarsRng'); load(SEED); asr(6); store(R2)
load(SEED); andi(0x20); shl(10); store(C)
call('SVP_StarsRng'); load(SEED); asr(5); andi(0x7ff); addi(0x200); store(R3)
dot(R1, R2, R3, M[0], M[1], M[2]); addm(VX); store(SX)
dot(R1, R2, R3, M[3], M[4], M[5]); addm(VY); store(SY)
dot(R1, R2, R3, M[6], M[7], M[8]); addm(VZ); store(SZ)
pm_write(PTR); load(SX); wr(); load(SY); wr(); load(SZ); wr()
ret()

# ---- mrand (MGDOTS.MC macro, bytes 01:A975..A97C): r0 = ror(swap(s)) ; r0 += s ; s = r0 + s + CY ; s++.
# In: SEED, C ($8000 = CY). Out: SEED, C3 ($8000 = CY after ADC, before INC).
label('SVP_StarsRng')
load(SEED); andi(0xff); shl(7); store(T)
load(SEED); asr(9); andi(0x7f); orm(T); orm(C); store(T)          # t = CY:swap(s)>>1
load(T); addm(SEED); store(U)                                      # u = t + s
carry(T, SEED, U); branch('SVP_StarsRngC', 'n1')
load(U); addm(SEED); branch('SVP_StarsRngW')
label('SVP_StarsRngC'); load(U); addm(SEED); addi(1)
label('SVP_StarsRngW'); store(W)                                   # w = u + s + CY
carry(U, SEED, W); store(C3)
load(W); addi(1); store(SEED)
ret()

# ---- minitdust 01:A861: m_rand = $19F8 (stored before the loop), 120 x 3 mrand words; the
# carry of each ADC feeds the next ROR; the first ROR takes the GSU CY at entry (INIT_CARRY).
label('SVP_StarsSeed')
imm(0x19f8); store(SEED)
imm(INIT_CARRY << 15); store(C)
imm(STATE + '+2'); store(CNT2); pm_write(CNT2)
imm(360); store(CNT2)
label('SVP_StarsSeedWord')
call('SVP_StarsRng'); load(C3); store(C); load(SEED); wr()
load(CNT2); subi(1); store(CNT2); branch('SVP_StarsSeedWord', 'z0')
imm(STATE); store(CNT2); pm_write(CNT2); imm(MAGIC); wr(); imm(0x19f8); wr()
imm(0x19f8); store(SEED)
ret()

# ---- PLOT: RAM0 $30 = bitmap x 0..255, $31 = bitmap y 0..191, $32 = nibble 1..15. Packed VR tile
# word base + (y>>4)*1024 + (x>>3)*32 + (y&15)*2 + ((x&7)>>2), nibble x&3 from bit 15 (as SVP_GridPlot).
label('SVP_StarPlot')
load(0x31); asr(4); store(ADDR); load(ADDR); shl(10); store(ADDR)
load(0x30); asr(3); store(TMP); load(TMP); shl(5); addm(ADDR); store(ADDR)
load(0x31); andi(15); shl(); addm(ADDR); store(ADDR)
load(0x30); andi(7); asr(2); addm(ADDR); addm(0xf6); store(ADDR)
load(0x30); andi(3); store(TMP); addi('SVP_StarMasks/2'); readrom(); store(MASK)
load(TMP); addi('SVP_StarShifts/2'); readrom(); store(SH)
product(0x32, SH); asr(); emit(0x003f); store(SH)                 # A.h = AL = nibble << shift
pm_read(ADDR); rd(); andm(MASK); orm(SH); store(VAL)
pm_write(ADDR); load(VAL); wr()
ret()
label('SVP_StarMasks'); emit(0x0fff, 0xf0ff, 0xff0f, 0xfff0)
label('SVP_StarShifts'); emit(4096, 256, 16, 1)
label('SVP_StarCol0')                                              # 14:BC6C, one byte per WORD
for i in range(0, 64, 16):
    emit(*rom[COL0 + i:COL0 + i + 16])
label('SVP_StarCol1')                                              # 14:BCAC
emit(*rom[COL1:COL1 + 16])

OUT.mkdir(parents=True, exist_ok=True)
(OUT / 'svp-stars.inc').write_text('\n'.join(lines) + '\n', encoding='ascii')
words = sum(len(l.split(',')) for l in lines if l.lstrip().startswith('dc.w'))
meta = dict(
    generator='tools/generate-svp-stars.py', rom=str(ROM_PATH.relative_to(ROOT)), rom_sha256=ROM_SHA256,
    units={'minitdust': '01:A861..A89B (call 03:BCD1 <- initmario3d 03:B85B <- initgame3d_l)',
           'mshowdust': '01:A8A6..AAD8', 'ztab': '14:896C (SVP_RomReciprocal)',
           'colour_mode0': '14:BC6C ' + rom[COL0:COL0 + 64].hex(), 'colour_mode1': '14:BCAC ' + rom[COL1:COL1 + 16].hex()},
    init_carry=INIT_CARRY, magic=f'${MAGIC:04X}', program_words=words,
    dram={'M4_GEO_STARS': '$301C40..$301C5B (14 WORDs, 68000 -> SVP per image)',
          'M4_STARS_STATE': '$31F600..$31F8D3 (362 WORDs, SVP-owned)'},
    ram={'RAM1': f'${0x100:03X}..${CNT2:03X}', 'RAM0': '$30..$32 plot args; reads $F6, $1F0, $1F1'},
    output_sha256=hashlib.sha256((OUT / 'svp-stars.inc').read_bytes()).hexdigest())
(OUT / 'svp-stars.json').write_text(json.dumps(meta, indent=1) + '\n', encoding='ascii')
print(f'Generated SVP_Stars: {words} program words -> {OUT / "svp-stars.inc"}')
