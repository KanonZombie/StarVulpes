"""Own SVP software sprites: port of the GSU `mssprite` 01:CCA8 (cmd8 type 5).

Specification: build/research/sprites.md (USA rev0; model `render_ssprite` of
tools/extract-sprite-textures.py, equal to the GSU bytes in 600/600 cases).
The 68000 passes, in painter order, a face record (kind 30) with the view
coordinates, the world size W = 2*sh_size + (s8(tx) << shift), the texture
of the current colframe and its size; SVP10 forwards it as a cmd8 type 5
record and SVP_Sprite projects (ztab 14:896C, centre 112/96, near doubling,
240 px cap), samples and writes the texels (index 0 transparent).
Outputs:
  build/svp-sprites.inc     SVP code, reciprocal/scale tables, packed textures
  build/level-sprites.inc   68000 table: per SVP model id the sprite entry
  build/svp-sprites.json    provenance (texture addresses, sizes, hashes)
Port difference (documented): the original also writes line y = 192 on the
small path; the port's bitmap has 192 lines (0..191) and clips it.
"""
import hashlib
import json
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rom_bytes = (ROOT / 'ref/Star Fox (USA).sfc').read_bytes()
assert hashlib.sha256(rom_bytes).hexdigest() == '3857b5294ea8f7468849437bb2d8271564e8a0ff30774622e9c872bcbd53a84d'
T = runpy.run_path(str(ROOT / 'tools/extract-sprite-textures.py'), run_name='sprite_textures')
rom = T['Rom'](rom_bytes)

lines = ['; Generated by tools/generate-svp-sprites.py: own SVP port of mssprite 01:CCA8.']


def emit(*words):
    lines.append('        dc.w ' + ','.join(f'${w & 65535:04x}' if isinstance(w, int) else w for w in words))


def label(name): lines.append(name + ':')
def load(slot): emit(0xe003, 0x0600 + slot)
def store(slot): emit(0x0e00 + slot)
def imm(value): emit(0xe003, 0x0830, value)
def call(name): emit(0x4800, name + '/2')
def ret(): emit(0x0065)
def readrom(): emit(0x4a10, 0xe003, 0x0031)

# Table word from the SVP ROM data block (src/system/core.asm, right after the
# 128 KiB program window): A = index -> A = word, read through PM4 (ROM read
# mode $080x, word address; a table never crosses a 64K-word page).
def romtab(name, minus=0):
    emit(0x8800, f'((SVP_{name}/2)&$ffff)-{minus}', 0x00e3, 0x08e0, f'$0800|((SVP_{name}/2)>>16)', 0x000c, 0xe003, 0x003c)
def branch(name, cond='always'):
    emit({'always': 0x4c00, 'z1': 0x4d50, 'z0': 0x4c50, 'n1': 0x4d70, 'n0': 0x4c70}[cond], name + '/2')
def add(slot): emit(0x8600 + slot)
def sub(slot): emit(0x2600 + slot)
def addi(v): emit(0x8800, v)
def subi(v): emit(0x2800, v)
def cmpi(v): emit(0x6800, v)
def andi(v): emit(0xa800, v)
def shl(n): emit(*([0x9003] * n))
def sar(n): emit(*([0x9002] * n))
def product(a, b):  # A32 = P = 2*a*b; A_hi = fq(a,b) = floor(a*b/2^15)
    load(a); emit(0x0013); load(b); emit(0x0023, 0x0037)


# RAM1 work slots (cmd8 uses RAM0 only; r4..r7 are not set in cmd8).
(X, Y, Z, S0, K, SX, SY, SS, HALF, X0, Y0, CLIPR, TEXADDR, TEXSIZE, STEP, WIDTH, COLBASE, ACC8, ACC7,
 ROWADDR, LINES, CNT, XC, YC, COL, WORD, TMP, TMP2, C128, SCALE2, ACCH, CFLAG, ROW, VIS, FRAC, R1,
 ADDR, NIB, PAR, VAL, MASK, NW, CNT2, BUILT) = range(0x1a0, 0x1cc)
PX, PY, PC = 0x30, 0x31, 0x32  # x+16, y+16 (as SVP_GridPlot), colour

label('SVP_Sprite')  # record slots 0x41 x, 0x42 y, 0x43 z, 0x44 W, 0x45 texture, 0x46 texsize
load(0x45); store(TEXADDR); load(0x46); store(TEXSIZE); imm(128); store(C128)
load(0x43); store(Z)
imm(128); sub(Z); branch('SVP_SprRet', 'n0')            # 01:CCAC z <= 128: nothing
load(0x41); store(X); load(0x42); store(Y); load(0x44); store(S0)
imm(0x3000); sub(Z); branch('SVP_SprZOk', 'n0'); imm(0x2fff); store(Z)
label('SVP_SprZOk')
label('SVP_SprNear')                                     # 01:CDFA z <= 256: double
imm(0x100); sub(Z); branch('SVP_SprFar', 'n1')
for s in (S0, X, Y, Z):
    load(s); shl(1); store(s)
branch('SVP_SprNear')
label('SVP_SprFar')
load(Z); sar(1); andi(0x7fff); romtab('RomReciprocal'); store(K)  # ztab[z & ~1]
product(X, K); addi(112); emit(0x8600 + 0x1f0); store(SX)   # + vanishing point offset (raster start)
product(Y, K); addi(96); emit(0x8600 + 0x1f1); store(SY)
product(S0, K); store(SS)
load(SS); cmpi(0); branch('SVP_SprRet', 'z1')            # 01:CCE8
imm(240); sub(SS); branch('SVP_SprSizeOk', 'n0'); imm(240); store(SS)
label('SVP_SprSizeOk')
load(SS); andi(1); store(TMP); load(SS); sar(1); add(TMP); store(HALF)
load(SX); sub(HALF); store(X0)
imm(1); sub(SS); store(TMP); load(X0); sub(TMP); branch('SVP_SprRet', 'n1')   # wholly left
load(X0); subi(223); branch('SVP_SprRet', 'n0')                               # x0 >= 223
load(SY); sub(HALF); store(Y0)
imm(223); sub(SS); store(CLIPR)
load(SS); sub(TEXSIZE); branch('SVP_SprSmall', 'n1')
branch('SVP_SprLarge')
label('SVP_SprRet'); ret()


def row_address(src):
    """ROWADDR = TEXADDR + row * texsize/4 words (packed 4 texels per WORD)."""
    load(TEXSIZE); cmpi(32); branch(f'SVP_SprRow64{src}', 'z0')
    load(src); shl(3); branch(f'SVP_SprRowAdd{src}')
    label(f'SVP_SprRow64{src}'); load(src); shl(4)
    label(f'SVP_SprRowAdd{src}'); add(TEXADDR); store(ROWADDR)


# Small path 01:CD71: S < texsize, 8.8 texel step per pixel.
label('SVP_SprSmall')
load(SS); addi('SVP_SprRecip/2'); readrom(); store(TMP)
load(TEXSIZE); shl(8); store(TMP2)
product(TMP2, TMP); store(STEP)
load(SS); store(WIDTH); imm(0); store(COLBASE); store(ACC8); load(X0); store(XC)
load(XC); cmpi(0); branch('SVP_SprSmallNoLeft', 'n0')
label('SVP_SprLeft')                                     # 01:CD9F left clip
load(ACC8); add(STEP); store(ACC8)
load(WIDTH); subi(1); store(WIDTH); branch('SVP_SprRet', 'z1')
load(XC); addi(1); store(XC); branch('SVP_SprLeft', 'n1')
product(ACC8, C128); andi(0xff); store(COLBASE)         # integer part only (sprites.md 4.6)
label('SVP_SprSmallNoLeft')
load(CLIPR); sub(XC); branch('SVP_SprSmallNoRight', 'n0')
load(WIDTH); store(CNT); load(XC); store(R1)
label('SVP_SprRight')
load(CNT); cmpi(0); branch('SVP_SprRightDone', 'z1')
imm(223); sub(R1); branch('SVP_SprRightDone', 'n1')
load(CNT); subi(1); store(CNT); load(R1); addi(1); store(R1); branch('SVP_SprRight')
label('SVP_SprRightDone')
load(WIDTH); sub(CNT); store(WIDTH)
label('SVP_SprSmallNoRight')
imm(0); store(ACC7); load(Y0); store(YC); load(SS); store(LINES)
label('SVP_SprSLine')
load(YC); cmpi(0); branch('SVP_SprSSkip', 'n1')
cmpi(192); branch('SVP_SprSSkip', 'n0')                 # port: line 192 clipped
product(ACC7, C128); andi(0xff); store(TMP); row_address(TMP)
imm(0); store(ACC8); load(XC); addi(16); store(PX); load(YC); addi(16); store(PY)
load(WIDTH); store(CNT); cmpi(0); branch('SVP_SprSSkip', 'z1')
emit(0x4800, 'SVP_SprBBegin/2')
label('SVP_SprSPix')
product(ACC8, C128); andi(0xff); add(COLBASE); store(COL)
emit(0x4800, 'SVP_SprTexel/2')
emit(0x4800, 'SVP_SprBPut/2')
load(ACC8); add(STEP); store(ACC8)
load(CNT); subi(1); store(CNT); branch('SVP_SprSPix', 'z0')
emit(0x4800, 'SVP_SprBEnd/2')
load(XC); addi(16); store(PX)
emit(0x4800, 'SVP_SprRowStart/2'); emit(0x4800, 'SVP_SprFlush/2')
label('SVP_SprSSkip')
load(ACC7); add(STEP); store(ACC7)
load(YC); addi(1); store(YC)
load(LINES); subi(1); store(LINES); branch('SVP_SprSLine', 'z0')
ret()

# Texel of ROWADDR/COL -> PC (packed nibbles, column 0 in bits 15..12).
label('SVP_SprTexel')
load(COL); sar(2); add(ROWADDR); readrom(); store(WORD)
load(COL); andi(3); cmpi(3); branch('SVP_SprT3', 'z1'); cmpi(2); branch('SVP_SprT2', 'z1')
cmpi(1); branch('SVP_SprT1', 'z1')
load(WORD); sar(4); branch('SVP_SprT1s')
label('SVP_SprT1'); load(WORD)
label('SVP_SprT1s'); sar(4); branch('SVP_SprT2s')
label('SVP_SprT2'); load(WORD)
label('SVP_SprT2s'); sar(4); branch('SVP_SprTDone')
label('SVP_SprT3'); load(WORD)
label('SVP_SprTDone'); andi(15); store(PC); ret()

# Large path 01:CE3F: S >= texsize, each texel repeated until the 16-bit
# accumulator carries. Accumulators and scale are even: kept halved (15 bits)
# so the carry/borrow is the sign of the 16-bit sum/difference.
label('SVP_SprLarge')
load(SS); sub(TEXSIZE); branch('SVP_SprLEqual', 'z1')
load(TEXSIZE); cmpi(32); branch('SVP_SprL64', 'z0')
load(SS); addi('SVP_SprScale32/2-32'); readrom(); branch('SVP_SprLScale')
label('SVP_SprL64'); load(SS); addi('SVP_SprScale64/2-64'); readrom(); branch('SVP_SprLScale')
label('SVP_SprLEqual'); imm(0x7fff)                     # ($FFFF & ~1) >> 1
label('SVP_SprLScale'); store(SCALE2)                    # tables hold scale >> 1
load(TEXSIZE); store(CNT)
imm(223); sub(X0); store(TMP); product(SCALE2, TMP); store(VIS)   # fq(scale>>1, 223-x0)
load(CNT); sub(VIS); subi(1); branch('SVP_SprLVisOk', 'n1')
load(VIS); store(CNT)
label('SVP_SprLVisOk')
imm(0); store(FRAC); store(COLBASE); load(X0); store(XC)
load(XC); cmpi(0); branch('SVP_SprLNoLeft', 'n0')
load(XC); emit(0x9006); store(TMP)                       # p = (scale>>1)*(-x); P = 2p
load(SCALE2); emit(0x0013); load(TMP); emit(0x0023, 0x0037)
store(TMP2); emit(0x003f); store(FRAC)                   # skip = (2p)>>16, frac = (2p)&$FFFF
load(TMP2); cmpi(0); branch('SVP_SprRet', 'n1')
load(TMP2); store(COLBASE); load(CNT); sub(TMP2); store(CNT); branch('SVP_SprRet', 'n1')
imm(0); store(XC)
label('SVP_SprLNoLeft')
load(CNT); cmpi(0); branch('SVP_SprRet', 'z1')
load(FRAC); sar(1); andi(0x7fff); store(FRAC)
imm(0); store(ROW); store(ACC7); load(Y0); store(YC)
imm(0xffff); store(BUILT)
label('SVP_SprLLine')
load(YC); cmpi(0); branch('SVP_SprLNext', 'n1')
imm(191); sub(YC); branch('SVP_SprRet', 'n1')
load(ROW); sub(BUILT); branch('SVP_SprLFlush', 'z1')    # same texture row: same pixels
row_address(ROW)
load(XC); addi(16); store(PX)
emit(0x4800, 'SVP_SprBBegin/2')
load(FRAC); store(ACCH)
load(CNT); subi(1); store(LINES); load(COLBASE); store(COL)
load(LINES); cmpi(0); branch('SVP_SprLLast', 'z1')
label('SVP_SprLTexel')
emit(0x4800, 'SVP_SprTexel/2')
label('SVP_SprLRep')
load(ACCH); add(SCALE2); store(CFLAG); andi(0x7fff); store(ACCH)
emit(0x4800, 'SVP_SprBPut/2')
load(CFLAG); cmpi(0); branch('SVP_SprLRep', 'n0')
load(COL); addi(1); store(COL)
load(LINES); subi(1); store(LINES); branch('SVP_SprLTexel', 'z0')
label('SVP_SprLLast')
emit(0x4800, 'SVP_SprTexel/2')
label('SVP_SprLLastRep')
imm(223 + 16); sub(PX); branch('SVP_SprLBuilt', 'n1')
load(ACCH); add(SCALE2); store(CFLAG); andi(0x7fff); store(ACCH)
emit(0x4800, 'SVP_SprBPut/2')
load(CFLAG); cmpi(0); branch('SVP_SprLLastRep', 'n0')
label('SVP_SprLBuilt')
emit(0x4800, 'SVP_SprBEnd/2')
load(ROW); store(BUILT)
label('SVP_SprLFlush')
load(XC); addi(16); store(PX); load(YC); addi(16); store(PY)
emit(0x4800, 'SVP_SprRowStart/2'); emit(0x4800, 'SVP_SprFlush/2')
label('SVP_SprLNext')
load(ACC7); sub(SCALE2); store(CFLAG); andi(0x7fff); store(ACC7)
load(YC); addi(1); store(YC)
load(CFLAG); cmpi(0); branch('SVP_SprLLine', 'n0')
load(ROW); addi(1); store(ROW); sub(TEXSIZE); branch('SVP_SprRet', 'z1')
branch('SVP_SprLLine')

# Row start: packed VR tile words (as SVP_GridPlot): word = base + (y>>4)*1024
# + (x>>3)*32 + (y&15)*2 + ((x&7)>>2), nibble x&3; along a row the word
# advances +1 then +31 every 4 pixels.
label('SVP_SprRowStart')
load(PY); subi(16); store(TMP); sar(4); andi(0x0fff); shl(10); store(ADDR)
load(TMP); andi(15); shl(1); add(ADDR); store(ADDR)
load(PX); sar(3); andi(0x1fff); shl(5); add(ADDR); store(ADDR)
load(PX); andi(4); sar(2); store(PAR); add(ADDR); add(0xf6); store(ADDR)
load(PX); andi(3); store(NIB); ret()
# Line buffer in RAM1 (r4: values 0x100.., r5: inverse masks 0x140..), one
# WORD per 4 pixels; BPut merges PC (if not 0) at nibble NIB and advances
# NIB/PX; Flush writes each WORD once: fully opaque WORDs directly, partial
# ones read-modify-write, empty ones skipped (VR packed layout as GridPlot).
label('SVP_SprBBegin')
emit(0x1c00); imm(0); emit(*([0x0534] * 64))
emit(0x1d40); imm(0xffff); emit(*([0x0535] * 64))
emit(0x1c00, 0x1d40)
load(PX); andi(3); store(NIB); ret()
label('SVP_SprBPut')
load(PC); cmpi(0); branch('SVP_SprBAdv', 'z1')
load(NIB); shl(4); add(PC); addi('SVP_SprNibVals/2'); readrom(); emit(0xc300, 0x0530)   # (r4) |= value
load(NIB); addi('SVP_SprNibInv/2'); readrom(); emit(0xa301, 0x0531)                     # (r5) &= ~mask
label('SVP_SprBAdv')
load(PX); addi(1); store(PX)
load(NIB); addi(1); store(NIB); cmpi(4); branch('SVP_SprBDone', 'z0')
imm(0); store(NIB); emit(0x0304, 0x0305)                                                  # r4++, r5++
label('SVP_SprBDone'); ret()
label('SVP_SprBEnd')
emit(0x1330); store(NW)                                                                   # A = r4
load(NIB); cmpi(0); branch('SVP_SprBEndDone', 'z1')
load(NW); addi(1); store(NW)
label('SVP_SprBEndDone'); ret()
label('SVP_SprFlush')
emit(0x1c00, 0x1d40)
load(NW); store(CNT2); cmpi(0); branch('SVP_SprRet', 'z1')
label('SVP_SprFLoop')
emit(0x0335); store(MASK); emit(0x0334); store(VAL)
load(MASK); cmpi(0xffff); branch('SVP_SprFAdvance', 'z1')
load(MASK); cmpi(0); branch('SVP_SprFWrite', 'z1')
load(ADDR); emit(0x00e3, 0x08e0, 0x0818, 0x000c)
emit(0xe003, 0x003c); emit(0xa600 + MASK); emit(0xc600 + VAL); store(VAL)
label('SVP_SprFWrite')
load(ADDR); emit(0x00e3, 0x08e0, 0x0818, 0x00c0)
load(VAL); emit(0x00c3)
label('SVP_SprFAdvance')
load(PAR); cmpi(0); branch('SVP_SprFOdd', 'z0')
load(ADDR); addi(1); store(ADDR); imm(1); store(PAR); branch('SVP_SprFNext')
label('SVP_SprFOdd'); load(ADDR); addi(31); store(ADDR); imm(0); store(PAR)
label('SVP_SprFNext')
load(CNT2); subi(1); store(CNT2); branch('SVP_SprFLoop', 'z0')
ret()
label('SVP_SprNibInv')
emit(0x0fff, 0xf0ff, 0xff0f, 0xfff0)
label('SVP_SprNibVals')
for nib in range(4):
    emit(*[(c << (12 - 4 * nib)) & 0xffff for c in range(16)])

# Tables. recip = 00:9647 (checked), scale = floor(texsize*65536/S) & ~1 (01:8183).
recip = [rom.w(0, (T['RECIPTAB'] + 2 * n) & 0xFFFF) for n in range(241)]
assert all(recip[n] == min(32767, 32768 // n) for n in range(1, 241)), 'recip table'
label('SVP_SprRecip')
for i in range(0, 241, 16):
    emit(*recip[i:i + 16])
for tex in (32, 64):
    label(f'SVP_SprScale{tex}')
    vals = [((0xFFFF if s == tex else (tex << 16) // s) & 0xFFFE) >> 1 for s in range(tex, 241)]
    for i in range(0, len(vals), 16):
        emit(*vals[i:i + 16])

# Sprite shapes drawn by mssprite (sprites.md section 0) and their SVP model id
# (tools/generate-intro-geometry.py), or None for level-only sprites reached
# through their level descriptor (tools/generate-level-shapes.py SPRITES); the
# spark B2A5 is not drawn (stub 01:A787).
SHAPES = [(3, 0xB11D), (4, 0xADD5), (11, 0xB139), (14, 0xB075), (15, 0xB091), (16, 0xB0AD),
          (19, 0xB101), (20, 0xB155), (21, 0xAEED), (22, 0xAF41), (None, 0xB219),
          (None, 0xAF5D), (None, 0xAF79), (None, 0xB005), (None, 0xB021), (None, 0xAD65), (None, 0xB1FD)]
# Per-object colour tables (alx+$20 coltab, path op setw $A0) that replace the
# header table of a sprite shape: (coltab 03:xxxx, shape whose size/shift it
# keeps). break_meteor 00:FAA5 path 4598: coltab 03:857F on AF79 (t03).
COLTAB_SPRITES = [(0x857F, 0xAF79)]
for _m in runpy.run_path(str(ROOT / 'tools/level-shapes.py'))['stage_modules']():  # tools/stages/*.py
    SHAPES += [(None, h) for h in sorted(_m.get('SPRITE_HEADERS', ())) if (None, h) not in SHAPES]
    COLTAB_SPRITES += list(_m.get('COLTAB_SPRITES', []))
textures, entries, report = {}, {}, []
for model, header in SHAPES:
    info = T['parse_shape'](rom, header)
    meta, words = T['colour_frames'](rom, info['col_ptr'])
    frames = []
    for w in words:
        tex = T['texture_from_word'](rom, w)
        key = '%02X%s' % (tex['texture_index'], 'H' if tex['nibble'] == 'high' else 'L')
        if key not in textures:
            rows, raw = T['texture_pixels'](rom, tex)
            assert tex['width'] == tex['height'] in (32, 64)
            textures[key] = dict(tex=tex, rows=rows, sha256=hashlib.sha256(raw).hexdigest())
        frames.append(key)
    entries[header] = dict(model=model, header=header, size=info['sh_size'], shift=info['shift'], frames=frames)
    report.append(dict(model=model, header='00:%04X' % header, sh_size=info['sh_size'], shift=info['shift'],
                       colour=meta, frames=frames))
coltab_entries = {}
for coltab, header in COLTAB_SPRITES:
    meta, words = T['colour_frames'](rom, coltab)
    frames = []
    for w in words:
        tex = T['texture_from_word'](rom, w)
        key = '%02X%s' % (tex['texture_index'], 'H' if tex['nibble'] == 'high' else 'L')
        if key not in textures:
            rows, raw = T['texture_pixels'](rom, tex)
            assert tex['width'] == tex['height'] in (32, 64)
            textures[key] = dict(tex=tex, rows=rows, sha256=hashlib.sha256(raw).hexdigest())
        frames.append(key)
    coltab_entries[coltab] = dict(e=entries[header], frames=frames)
    report.append(dict(coltab='03:%04X' % coltab, shape='00:%04X' % header, colour=meta, frames=frames))
texture_tail = []
inline_words = 0
INLINE_TEXTURE_WORDS = 16384
for key, t in textures.items():
    words = len(t['rows']) ** 2 // 4
    target = lines if inline_words + words <= INLINE_TEXTURE_WORDS else texture_tail
    if target is lines:
        inline_words += words
    target.append(f'SVP_SprTex{key}:')
    for row in t['rows']:
        packed = [(row[i] << 12) | (row[i + 1] << 8) | (row[i + 2] << 4) | row[i + 3] for i in range(0, len(row), 4)]
        target.append('        dc.w ' + ','.join(f'${word:04x}' for word in packed))
texture_tail.append('SVP_SprTexturesEnd:')
(ROOT / 'build/svp-sprites.inc').write_text('\n'.join(lines) + '\n', encoding='ascii')
(ROOT / 'build/svp-sprites-tail.inc').write_text('\n'.join(texture_tail) + '\n', encoding='ascii')

# 68000 table: per SVP model id 0..23 a pointer (0 = not a sprite); entry:
# dc.w sh_size, shift, n; n x (texture WORD address, texsize).
m = ['; Generated by tools/generate-svp-sprites.py (mssprite entries per SVP model id;',
     '; level effects use M4SpriteH<header> from their descriptor).', 'M4SpriteModels:']
by_model = {e['model']: h for h, e in entries.items() if e['model'] is not None}
for model in range(24):
    m.append(f'        dc.l M4SpriteH{by_model[model]:04X}' if model in by_model else '        dc.l 0')
for header, e in entries.items():
    m.append(f'M4SpriteH{header:04X}: ;00:{header:04X}')
    m.append(f'        dc.w {e["size"]},{e["shift"]},{len(e["frames"])}')
    for key in e['frames']:
        m.append(f'        dc.w SVP_SprTex{key}/2,{textures[key]["tex"]["width"]}')
m.append('M4SpriteColtabs: ;coltab WORD, entry (0 ends)')
for coltab, c in coltab_entries.items():
    m.append(f'        dc.w ${coltab:04x}')
    m.append(f'        dc.l M4SpriteC{coltab:04X}')
m.append('        dc.w 0')
for coltab, c in coltab_entries.items():
    m.append(f'M4SpriteC{coltab:04X}: ;coltab 03:{coltab:04X}')
    m.append(f'        dc.w {c["e"]["size"]},{c["e"]["shift"]},{len(c["frames"])}')
    for key in c['frames']:
        m.append(f'        dc.w SVP_SprTex{key}/2,{textures[key]["tex"]["width"]}')
(ROOT / 'build/level-sprites.inc').write_text('\n'.join(m) + '\n', encoding='ascii')
