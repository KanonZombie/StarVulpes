"""Own SSP1601 command 7: original 1bpp text into a packed MD framebuffer.

The host supplies already-projected positions and a Q0.16 scale. The SVP
consumes original glyph rows; it performs both Bresenham sampling and pixel
rasterization. This is the graphics backend, not a camera or game clock.

Mailbox +20: descriptor count 0..64. DRAM 301000: seven words per descriptor:
original signed x/y (224x192 space), scale 1..65535, colour 1..15, DSP ROM
string pointer, length 1..16, projected char width 0..16. A=1..Z=26. Both
X receives+16; normal Y stays in0..191 for the256x192 output. The CPU
reference retains both+16 and256x224. M4_RENDER_TOP removes the vertical
padding without modifying original sampling. Normal clear:304000..309FFF,
12288 words, tile-major; original source coordinates remain224x192.
Publish checksum modulo 65536 at +16, result word count, sequence echo and
ACK in that order. Invalid descriptors publish result 0; the host must not
present that buffer. Ownership lasts through host transfer, as with cmd 6.

Encoding reference: local Genesis Plus GX core/cart_hw/svp/ssp16.c. Only N/Z
conditions are used: that implementation does not implement carry/L. The
unsigned subtraction borrow is recovered explicitly from operand signs.
The source msprint Y loop draws row 0 before subtraction; its X loop
subtracts before emitting. Preserve that asymmetry, including tiny scales.
Original whole-character clipping also matters: X<=0 skips the glyph and
advances by char width without changing the sampler; X>222-char width ends
the row. Y outside 0..191 skips the row. These are ROM msprint rules, not
generic per-pixel clipping; the final pixel bound is only a buffer guard.
"""
from pathlib import Path
import runpy

ROOT = Path(__file__).resolve().parents[1]
lines = [
    '; Generated by tools/generate-svp-text.py; own SSP1601 text raster.',
    '; cmd7: count at 300014, seven-word descriptors at 301000.',
    '; Output height selected by M4_RENDER_HEIGHT; MD tile-major.',
    '; RAM0: 00 seq,01 descriptor ptr,02 count,03 yacc,04 xacc,05 src row,',
    '; 06 y,07 x,08 string cursor,09 chars left,0A glyph row,0B bits left,',
    '; 0C bitmap row,0D address,0E old accumulator; 10..16 descriptor,',
    '; 17 colour table base. X/Y scratch; sequence restored before ACK.',
]


def emit(*words):
    lines.append('        dc.w ' + ','.join(
        f'${word & 65535:04x}' if isinstance(word, int) else word
        for word in words))


def label(name):
    lines.append(name + ':')


def load(slot):
    emit(0xe003, 0x0600 + slot)  # Clear AL: arithmetic uses upper-word integers.


def store(slot):
    emit(0x0e00 + slot)


def immediate(value):
    emit(0xe003, 0x0830, value)


def branch(name, condition='always'):
    emit({'always': 0x4c00, 'z1': 0x4d50, 'z0': 0x4c50,
          'n1': 0x4d70}[condition], name + '/2')


def advance(slot, amount):
    load(slot)
    emit(0x8800, amount)
    store(slot)


def read_rom():
    # LD X,(A) reads a DSP program-ROM word. Clear AL before using its value.
    emit(0x4a10, 0xe003, 0x0031)


def accumulator_step(slot, name, borrowed, no_borrow):
    """Subtract unsigned scale, retain modulo16 result and branch on borrow.

    If old/scale signs differ, old high-bit 0 determines borrow. If their
    signs agree the difference is within -32767..32767, so N is sufficient.
    This also handles scale FFFF and odd scales without rounding them.
    """
    load(slot)
    store(0x0e)
    emit(0x2612)
    store(slot)
    load(0x0e)
    emit(0xe612, 0xa800, 0x8000)
    branch(name + 'SameSign', 'z1')
    load(0x0e)
    emit(0xa800, 0x8000)
    branch(borrowed, 'z1')
    branch(no_borrow)
    label(name + 'SameSign')
    load(slot)
    emit(0x6800, 0)
    branch(borrowed, 'n1')
    branch(no_borrow)


fb=runpy.run_path(str(ROOT/'tools/svp-framebuffer.py'))
label('SVP_Text')
emit(0x0032)
store(0)
fb['setup'](globals(),'SVP_Text','SVP_TextInvalid')  # Keep request Y before clearing/using it as a loop register.
immediate(0x0800)
store(1)
emit(0x08e0, 10, 0x08e0, 0x0018, 0x000c, 0xe003, 0x003c)
store(2)
# Count validation includes high-bit values, so subtraction cannot wrap them
# into the accepted range. A zero-descriptor request is a valid clear job.
emit(0xa800, 0xff80)
branch('SVP_TextInvalid', 'z0')
load(2)
emit(0x6800, 65)
branch('SVP_TextClear', 'n1')
branch('SVP_TextInvalid')
label('SVP_TextClear')
fb['pm'](globals(),True);emit(0x0820,0)
immediate('M4_RENDER_WORDS')
label('SVP_TextClearWord')
emit(0x00c2, 0x2800, 1)
branch('SVP_TextClearWord', 'z0')
load(2)
emit(0x6800, 0)
branch('SVP_TextDone', 'z1')

label('SVP_TextDescriptor')
load(1)
emit(0x00e3, 0x08e0, 0x0818, 0x000c)
for slot in range(0x10, 0x17):
    emit(0xe003, 0x003c)
    store(slot)
load(0x12)
emit(0x6800, 0)
branch('SVP_TextInvalid', 'z1')
for slot, maximum in ((0x13, 15), (0x15, 16)):
    load(slot)
    emit(0xa800, 0xffe0)
    branch('SVP_TextInvalid', 'z0')
    load(slot)
    emit(0x6800, 0)
    branch('SVP_TextInvalid', 'z1')
    emit(0x6800, maximum + 1)
    branch('SVP_TextValid' + str(slot), 'n1')
    branch('SVP_TextInvalid')
    label('SVP_TextValid' + str(slot))
load(0x16)
emit(0xa800, 0xffe0)
branch('SVP_TextInvalid', 'z0')
load(0x16)
emit(0x6800, 17)
branch('SVP_TextValidWidth', 'n1')
branch('SVP_TextInvalid')
label('SVP_TextValidWidth')
load(0x13)
emit(0x9003, 0x9003, 0x8800, 'SVP_TextColours/2')
store(0x17)
for slot in (3, 5):
    immediate(0)
    store(slot)
load(0x11)
store(6)

label('SVP_TextSourceRow')
# Original msprint draws source row 0 BEFORE stepping its Y accumulator.
# X uses the different, subtract-before-emission order below. This makes
# scale $6000 select Y rows 0,1,3,6,9,11,14 (seven destination rows).
load(6)
emit(0x6800, 0)
branch('SVP_TextNextDestRow', 'n1')
emit(0x6800, 192)
branch('SVP_TextVisibleRow', 'n1')
branch('SVP_TextNextDestRow')
label('SVP_TextVisibleRow')
# Original coordinates translate by(+16,+16-M4_RENDER_TOP).
# Tile-major word row: (y&F8)*64 + (y&7)*2 + 2000 + 400 + 20.
load(6)
lines.append('        if def(M4_VR_DMA)')
emit(0xa800,0xf0,*([0x9003]*6),0x8800,64,0x86f6)
store(0x0c);load(6);emit(0xa800,15,0x9003,0x860c)
lines.append('        else')
emit(0xa800, 0x00f8, *([0x9003] * 6), 0x8800, '($2420-M4_RENDER_TOP*64)')
store(0x0c)
load(6)
emit(0xa800, 7, 0x9003, 0x860c)
lines.append('        endif')
store(0x0c)
for source, destination in ((0x10, 7), (0x14, 8), (0x15, 9)):
    load(source)
    store(destination)
immediate(0)
store(4)  # Horizontal sampling continues across glyph boundaries.

label('SVP_TextGlyph')
load(8)
read_rom()
store(0x0d)
emit(0xa800, 0xffe0)
branch('SVP_TextInvalid', 'z0')
load(0x0d)
emit(0x6800, 0)
branch('SVP_TextInvalid', 'z1')
emit(0x6800, 27)
branch('SVP_TextValidGlyph', 'n1')
branch('SVP_TextInvalid')
label('SVP_TextValidGlyph')
load(7)
emit(0x6800, 0)
branch('SVP_TextSkipGlyph', 'n1')
branch('SVP_TextSkipGlyph', 'z1')
immediate(222)
emit(0x2616, 0x2607)  # Original right threshold: 224 - char width - 2.
branch('SVP_TextNextDestRow', 'n1')
load(0x0d)
emit(0x2800, 1, *([0x9003] * 4), 0x8605,
     0x8800, 'SVP_TextFont/2')
read_rom()
store(0x0a)
immediate(16)
store(0x0b)

label('SVP_TextSourcePixel')
accumulator_step(4, 'SVP_TextX', 'SVP_TextEmitPixel', 'SVP_TextNextSourcePixel')
label('SVP_TextEmitPixel')
load(0x0a)
emit(0xa800, 0x8000)
branch('SVP_TextNextDestPixel', 'z1')
load(7)
emit(0x6800, 0)
branch('SVP_TextNextDestPixel', 'n1')
emit(0x6800, 224)
branch('SVP_TextVisiblePixel', 'n1')
branch('SVP_TextNextDestPixel')
label('SVP_TextVisiblePixel')
# The row already accounts for y. Add (x&F8)*2 + ((x&4)>>2).
load(7)
emit(0xa800,0x00f8,0x9003)
lines.append('        if def(M4_VR_DMA)')
emit(0x9003)
lines.append('        endif')
emit(0x860c)
store(0x0d)
load(7)
emit(0xa800, 4, 0x9002, 0x9002, 0x860d)
emit(0x00e3, 0x08e0, 0x0418, 0x00c0)
load(7)
emit(0xa800, 3, 0x8617)
read_rom()
emit(0x00c3)  # Zero nibbles preserve neighbours; colour is guaranteed nonzero.
label('SVP_TextNextDestPixel')
advance(7, 1)
label('SVP_TextNextSourcePixel')
load(0x0a)
emit(0x9003)
store(0x0a)
load(0x0b)
emit(0x2800, 1)
store(0x0b)
branch('SVP_TextSourcePixel', 'z0')
branch('SVP_TextNextGlyph')
label('SVP_TextSkipGlyph')
load(7)
emit(0x8616)
store(7)  # Original skip advances by projected char width, sampler unchanged.
label('SVP_TextNextGlyph')
advance(8, 1)
load(9)
emit(0x2800, 1)
store(9)
branch('SVP_TextGlyph', 'z0')
label('SVP_TextNextDestRow')
advance(6, 1)
label('SVP_TextYStep')
accumulator_step(3, 'SVP_TextY', 'SVP_TextNextDrawRow', 'SVP_TextSkipSourceRow')
label('SVP_TextSkipSourceRow')
advance(5, 1)
emit(0x6800, 16)
branch('SVP_TextNextDescriptor', 'z1')
branch('SVP_TextYStep')
label('SVP_TextNextDrawRow')
advance(5, 1)
emit(0x6800, 16)
branch('SVP_TextSourceRow', 'z0')
label('SVP_TextNextDescriptor')
advance(1, 7)
load(2)
emit(0x2800, 1)
store(2)
branch('SVP_TextDescriptor', 'z0')

label('SVP_TextDone')
fb['pm'](globals())
fb['checksum'](globals(),'SVP_Text')
emit(0xe003, 0x0031, 0x08e0, 8, 0x08e0, 0x0018, 0x00c0, 0x00c3)
load(0)
emit(0x0023)
immediate('M4_RENDER_WORDS')
branch('SVP_PublishResult')
label('SVP_TextInvalid')
emit(0x08e0, 8, 0x08e0, 0x0018, 0x00c0, 0x08c0, 0)
load(0)
emit(0x0023)
immediate(0)
branch('SVP_PublishResult')

label('SVP_TextColours')
for colour in range(16):
    emit(*(colour << (12 - pixel * 4) for pixel in range(4)))
font = (ROOT / 'build/intro-text-font.bin').read_bytes()
if len(font) != 26 * 16 * 2:
    raise ValueError('Expected 26 original 16-row glyphs, 832 bytes')
label('SVP_TextFont')
for offset in range(0, len(font), 2):
    emit(int.from_bytes(font[offset:offset + 2], 'little'))
for name in ('Nintendo', 'Presents'):
    string = (ROOT / f'build/intro-{name.lower()}.bin').read_bytes()
    if not string or string[-1] != 0 or any(not 1 <= x <= 26 for x in string[:-1]):
        raise ValueError(f'Invalid original {name} string')
    label('SVP_Text' + name)
    emit(*string)
label('SVP_TextDataEnd')
(ROOT / 'build/svp-text.inc').write_text('\n'.join(lines) + '\n', encoding='ascii')
print('Generated SVP cmd7: original text sampling and 256x224 pixel raster')
