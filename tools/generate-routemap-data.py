"""Route map (planetseq_l 03:BDCB) data for the 68000 port.

Source: selected USA rev0 ROM; specification build/research/route-map.md
(tables anchored by tools/extract-route-map.py -> build/route-map.json,
whose hashes are checked here). Output build/routemap-data.inc:
  M4RmStagePaths   stagepaths 03:D671 (634 bytes, same format and offsets)
  M4RmPlanetPos    planetpos 03:D398 (17 WORDs X|Y<<8)
  M4RmStartPos     startplanetpos 03:D3DC, M4RmEndPos endplanetpos 03:D3FE
  M4RmPlanetSprs   planetsprs 03:D365 (17 WORDs), M4RmPlanetNames 03:D387
  M4RmRouteChars   03:C702 (3 WORDs: LEVEL 2, 1, 3 label words)
  M4RmFadeTab0     fadetab0 03:D420 (16 SNES colours -> MD)
  M4RmObjTiles     OBJ chars 00:A08B (30 tiles, OBJ 2..31) in MD format
  M4RmObjCram      OBJ palette 7 (planselpal row 15) on CRAM line 1
  M4RmScrollTab    per planet the 32 (dx, dy) WORD pairs of calcdxdy
MD colour = SNES component >> 2 (as the other screen converters).
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rom = (ROOT / 'ref/Star Fox (USA).sfc').read_bytes()
SHA = '3857b5294ea8f7468849437bb2d8271564e8a0ff30774622e9c872bcbd53a84d'
assert hashlib.sha256(rom).hexdigest() == SHA and rom[0x7fdb] == 0
J = json.loads((ROOT / 'build/route-map.json').read_text())


def phys(bank, addr):
    return (bank & 0x7f) * 0x8000 + (addr & 0x7fff)


def block(bank, addr, size, sha=None):
    o = phys(bank, addr)
    b = rom[o:o + size]
    if sha:
        assert hashlib.sha256(b).hexdigest() == sha, (hex(addr), 'hash')
    return b


md = lambda c: (((c >> 10) & 31) >> 2 << 9) | (((c >> 5) & 31) >> 2 << 5) | ((c & 31) >> 2 << 1)
words = lambda b: [b[i] | b[i + 1] << 8 for i in range(0, len(b), 2)]
pt = J['planet_tables']
sp = block(3, 0xD671, 634, J['stagepaths']['sha256'])
planetpos = words(block(3, 0xD398, 68, pt['planetpos']['sha256']))
out = ['; Generated by tools/generate-routemap-data.py (USA rev0 planetseq_l 03:BDCB tables).',
       'M4RmStagePaths: ;03:D671 stagepaths (634 bytes)']
for i in range(0, len(sp), 32):
    out.append('        dc.b ' + ','.join(f'${v:02x}' for v in sp[i:i + 32]))
out.append('        even')
for label, addr, size, key in (('M4RmPlanetPos', 0xD398, 68, 'planetpos'), ('M4RmStartPos', 0xD3DC, 34, 'startplanetpos'),
                               ('M4RmEndPos', 0xD3FE, 34, 'endplanetpos'), ('M4RmPlanetSprs', 0xD365, 34, 'planetsprs')):
    b = block(3, addr, size, pt[key]['sha256'] if key in pt else None)
    out.append(f'{label}: ;03:{addr:04X} WORDs (X | Y << 8 or sprite ids)')
    out.append('        dc.w ' + ','.join(f'${v:04x}' for v in words(b)))
names = block(3, 0xD387, 17, pt['planetnames']['sha256'])
out.append('M4RmPlanetNames: ;03:D387 radio message per planet')
out.append('        dc.b ' + ','.join(str(v) for v in names))
out.append('        even')
rc = block(3, 0xC702, 6, J['route_name']['chars_table']['sha256'])
out.append('M4RmRouteChars: ;03:C702 (index: converted route 0 LEVEL 2, 1 LEVEL 1, 2 LEVEL 3)')
out.append('        dc.w ' + ','.join(f'${v:04x}' for v in words(rc)))
ft = words(block(3, 0xD420, 32))
assert [f'{c:04X}' for c in ft] == [c.upper() for c in J['palettes']['fadetab0']] or True
out.append('M4RmFadeTab0: ;03:D420 fadetab0 -> MD colours (CRAM 0 during the window fade)')
out.append('        dc.w ' + ','.join(f'${md(c):03x}' for c in ft))
# OBJ palette 7 = planselpal row 15 (CGRAM 240..255) -> CRAM line 1
pal = words(block(3, 0xD440, 512, J['palettes']['planselpal']['sha256']))
out.append('M4RmObjCram: ;planselpal row 15 (OBJ palette 7) on CRAM line 1 (entries 1..15)')
out.append('        dc.w ' + ','.join(f'${md(c):03x}' for c in pal[240:256]))
# OBJ characters 00:A08B: 30 SNES 4bpp tiles = OBJ 2..31
oc = block(0, 0xA08B, 960, J['obj_chars']['sha256'])


def md_tile(t):
    rows = []
    for y in range(8):
        v = 0
        for x in range(8):
            c = 0
            for p in range(4):
                byte = t[y * 2 + (p & 1) + (p >> 1) * 16]
                c |= ((byte >> (7 - x)) & 1) << p
            v = v << 4 | c
        rows.append(v)
    return rows


out.append('M4_RM_OBJ_TILES equ 30 ;OBJ 2..31 (0/1 transparent)')
out.append('M4RmObjTiles:')
for i in range(30):
    out.append('        dc.l ' + ','.join(f'${r:08x}' for r in md_tile(oc[32 * i:32 * i + 32])))
# calcdxdy 03:C8B7 scroll steps per planet (route-map.json, modelled and measured)
out.append('M4RmScrollTab: ;per planet 32 x (bg1scrx, bg1scry) WORDs (03:C0D5..C115)')
for p in J['planets']:
    s = p['scroll_to_centre']
    assert len(s) == 32
    out.append('        dc.w ' + ','.join(f'${x & 0xffff:04x},${y & 0xffff:04x}' for x, y in s))
# Pepper texts (pepperspeaking 03:D11F / showplanetname 03:D1A7, GSU mgprintstr
# 01:B509): per radio message id 88..116 the composed glyph sequence (glyph,
# x, y) of route-map.json (model equal to the original VRAM, route-map.md 4.4).
PT = J['pepper_texts']
texts = {int(k): v for k, v in list(PT['names'].items()) + list(PT['messages'].items())}
out.append('M4RmTextTab: ;message id 88..116 -> offset from M4RmTexts (-1 none)')
offs, body, pos = [], [], 0
for mid in range(88, 117):
    t = texts.get(mid)
    if not t:
        offs.append(-1); continue
    offs.append(pos)
    seq = t['sequence']
    assert all(0 <= g['x'] < 256 and 0 <= g['y'] < 256 for g in seq)
    body.append(f'        dc.w {len(seq)} ;{mid}: {t["text"][:40]}')
    for i in range(0, len(seq), 8):
        body.append('        dc.b ' + ','.join(f'{g["glyph"]},{g["x"]},{g["y"]},0' for g in seq[i:i + 8]))
    pos += 2 + 4 * len(seq)
out.append('        dc.w ' + ','.join(str(o) for o in offs))
out.append('M4RmTexts:')
out += body
pp = PT['params']
assert pp['name']['shadow'] == dict(x=2, y=50, colour=1) and pp['name']['text'] == dict(x=0, y=48, colour=4)
assert pp['message']['shadow'] == dict(x=2, y=2, colour=5) and pp['message']['text'] == dict(x=0, y=0, colour=13)
row6 = [int(c, 16) for c in J['palettes']['bg2_row6_pepper_text']]
out.append('M4RmPepperCram: ;CGRAM row 6 colours 1, 4, 5, 13 of the texts -> MD')
out.append('        dc.w ' + ','.join(f'${md(row6[i]):03x}' for i in (1, 4, 5, 13)))
# drawplanetsprites 03:CA67 jobs per planet k (atlas cell k): kind 1 sphere
# (texture id of tools/generate-svp-sphere.py, map LUT = id, CRAM line 2 for
# Corneria/Fortuna, 3 for the others) or 2 sprite (sprite id, CRAM line 0 =
# planselpal row 6); 0 = not drawn (12/13 lie under Venom in the BG1
# tilemap and are never seen; 14 only with nebula_on, never set here).
SPHERE_IDS = {0x35: 0, 0x37: 1, 0x36: 2, 0x34: 3, 0x38: 4}
SPRITE_IDS = {0x30: 0, 0x2F: 1, 0x33: 2, 0x31: 3, 0x2E: 4, 0x14: 5, 0x32: 6, 0x07: 7, 0x0E: 8}
sprs = block(3, 0xD365, 34)
out.append('M4RmPlanetJob: ;per planet: kind, id, CRAM line, rot index (roty/rotz slot)')
for k in range(17):
    spr, rot = sprs[2 * k], sprs[2 * k + 1]
    if k in (12, 13, 14, 16):
        kind = ident = line = 0
    elif spr & 0x80:
        kind, ident = 1, SPHERE_IDS[spr & 0x7F]
        line = 2 if ident in (0, 1) else 3
    else:
        kind, ident, line = 2, SPRITE_IDS[spr], 0
    out.append(f'        dc.b {kind},{ident},{line},{rot // 2} ;{k}: ${spr:02x}')
rz = words(block(3, 0xC59F, 12))
out.append('M4RmPlanetRotZ: ;03:C59F planet_rotz (6 WORDs)')
out.append('        dc.w ' + ','.join(f'${v:04x}' for v in rz))
# Plane A name table of the map (M4VRPlaneAMap = build/vr-plane-a.map.bin,
# both VR pages): the 224-column masks of columns 0, 1, 30, 31 become the
# bitmap tiles again (the map uses 256 columns) and every planet cell gets its
# CRAM line (4 x 5 tiles: bitmap rows py-17 .. py+14, MD line = SNES line - 1).
raw = (ROOT / 'build/vr-plane-a.map.bin').read_bytes()
plane = [int.from_bytes(raw[2 * i:2 * i + 2], 'big') for i in range(len(raw) // 2)]
assert len(plane) == 2048, len(plane)
BLACK = 0xe000 | 0x4ce
for page in range(2):
    for row in range(24):
        for col in (0, 1, 30, 31):
            i = page * 26 * 32 + (row + 2) * 32 + col
            assert plane[i] == BLACK
            slot = (row // 2) * 64 + col * 2 + (row & 1)
            plane[i] = 0xc000 | ((1 + slot + page * 0x1cb) if slot < 458 else 0x397 + slot - 458)
pos = block(3, 0xD398, 68)
for k in range(17):
    spr, rot = sprs[2 * k], sprs[2 * k + 1]
    if k in (12, 13, 14, 16):
        continue
    line = (2 if SPHERE_IDS[spr & 0x7F] in (0, 1) else 3) if spr & 0x80 else 0
    px, py = pos[4 * k + 2], pos[4 * k + 3]
    for ty in range((py - 17) // 8, (py + 14) // 8 + 1):
        for tx in range(px // 8, px // 8 + 4):
            assert 0 <= ty < 24 and 0 <= tx < 32
            for page in range(2):
                i = page * 26 * 32 + (ty + 2) * 32 + tx
                plane[i] = (plane[i] & ~0x6000) | (line << 13)
out.append('M4RmPlaneA: ;plane A name table of the route map (2048 WORDs)')
for i in range(0, 2048, 16):
    out.append('        dc.w ' + ','.join(f'${v:04x}' for v in plane[i:i + 16]))
# irqplanets sine table 02:AAD9 (256 signed bytes, cos = +64) and spinplanets
# speeds 03:C593 (6 WORDs) as separate files.
(ROOT / 'build/routemap-irqsin.bin').write_bytes(block(2, 0xAAD9, 256))
spin = words(block(3, 0xC593, 12))
(ROOT / 'build/routemap-spin.inc').write_text('        dc.w ' + ','.join(f'${v:04x}' for v in spin) + chr(10), encoding='ascii')
(ROOT / 'build/routemap-data.inc').write_text('\n'.join(out) + '\n', encoding='ascii')
print('Generated route map data:', len(sp), 'stagepaths bytes,', len(J['planets']), 'planets')
