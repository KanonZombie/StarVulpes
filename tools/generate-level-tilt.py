"""Corneria BG2 roll tilt tables for the Mega Drive plane B.

Specification: build/research/bg-tilt.md (USA rev0; calcbg2voffsets 02:DB54,
tables bg2ptrs 00:8C15 -> 00:8C29..8D69, executed 5000/5000 against the
model tools/bg-tilt-model.py). Output build/level-tilt.inc:
  M4TiltTables: 8 x 32 BYTEs, offset per SNES 8 px column (index = hi|plrotz|&7)
The 68000 adds bg2scroll and mirrors them for plrotz < 0; the per-line
horizontal shear (mrotplanet 06:FB87) is computed at run time.
"""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rom = (ROOT / 'ref/Star Fox (USA).sfc').read_bytes()
assert hashlib.sha256(rom).hexdigest() == '3857b5294ea8f7468849437bb2d8271564e8a0ff30774622e9c872bcbd53a84d'
word = lambda a: int.from_bytes(rom[a & 0x7FFF:(a & 0x7FFF) + 2], 'little')
ptrs = [word(0x8C15 + 2 * i) for i in range(8)]
assert all(0x8C29 <= p <= 0x8D69 and (p - 0x8C29) % 64 == 0 for p in ptrs), ptrs
lines = ['; Generated by tools/generate-level-tilt.py from bg2ptrs 00:8C15 (USA rev0).', 'M4TiltTables:']
for i, p in enumerate(ptrs):
    raw = [word(p + 2 * k) for k in range(32)]
    assert all(v & 0xBE00 == 0 and v & 0x4000 for v in raw), (i, 'BG2 bit $4000, no other flags')
    vals = [v & 0x1FF for v in raw]
    assert all(0 < v <= 32 for v in vals), (i, vals)
    assert all(0 <= vals[k] - vals[k + 1] <= 1 for k in range(31)), (i, 'monotonic step 0/1')
    lines.append(f'        dc.b {",".join(map(str, vals))} ;00:{p:04X}')
(ROOT / 'build/level-tilt.inc').write_text('\n'.join(lines) + '\n', encoding='ascii')
print('Generated BG2 tilt tables: 8 x 32 columns')
