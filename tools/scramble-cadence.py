"""Generate the port's phase-regularized SCRAMBLE presentation schedule."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Logical tick and elapsed NTSC VBlanks measured at strategy transitions.
# These are presentation targets for the port. Per-frame stalls are omitted.
POINTS = [(0, 0), (160, 1005), (192, 1261), (246, 1546), (305, 1839), (321, 1905)]

capture = ROOT / 'evidence/starfox-original-scramble.json'
if capture.is_file():
    reference = json.loads(capture.read_text())
    assert reference['rom_sha256'] == '3857b5294ea8f7468849437bb2d8271564e8a0ff30774622e9c872bcbd53a84d'
    points = []
    for strategy in (0x0B8134, 0x0B8211, 0x0B9031, 0x0B9085, 0x0B90DB, 0x0BBBE3):
        sample = next(q for q in reference['samples'][reference['reset_vblank']:]
                      if any(o['obj'] == q['player'] and o['strat'] == strategy for o in q['objects']))
        points.append((sample['gameframe'] - 256, sample['vblank']))
    base = points[0][1]
    assert [(tick, blank - base) for tick, blank in points] == POINTS

deadlines = [0]
for (start, first), (end, last) in zip(POINTS, POINTS[1:]):
    ticks = end - start
    deadlines.extend(first + (step * (last - first) + ticks // 2) // ticks
                     for step in range(1, ticks + 1))
assert all(0 < b - a <= 8 for a, b in zip(deadlines, deadlines[1:]))
lines = ['; Generated by tools/scramble-cadence.py.', 'M4ScTimingDeadlines:']
for offset in range(0, len(deadlines), 12):
    lines.append('        dc.w ' + ','.join(map(str, deadlines[offset:offset + 12])))
lines.append('M4ScTimingDeadlinesEnd:')
(ROOT / 'build/scramble-cadence.inc').write_text('\n'.join(lines) + '\n', encoding='ascii')
print(f'PASS SCRAMBLE: {len(deadlines)} deadlines')
