"""SVP13: raster(k-1), geometry(k), BSP(k), faces(k), one host request.

Uses the existing command bodies and completion protocol. The raster sub-result
is published in a separate DRAM header before geometry can overwrite its inputs.
RAM A $F2..$F4 is reserved across all four bodies (stage, result, sequence).
"""
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
A = runpy.run_path(str(ROOT / 'tools/generate-svp-bsp.py'))['Asm']
a = A()
H = '((M4_CHAIN_HDR-$300000)/2)'
STAGE, RESULT, SEQ = 0xf2, 0xf3, 0xf4


def read(offset):
    a.read_dram_i(H + f'+{offset}')
    a.clr(); a.pm_get()


def write(offset):
    a.pmc_i(H + f'+{offset}'); a.pmc_i(0x0018); a.pm_write_prog(); a.pm_put()


def count(offset):
    read(offset)
    a.pmc_i(10); a.pmc_i(0x0018); a.pm_write_prog(); a.pm_put()


a.label('SVP_Chain')
a.a_y(); a.st(SEQ)
read(0); a.tst(); a.br('SVP_ChainGeometry', 'z')
a.ldi(1); a.st(STAGE); a.br('SVP_IntroRaster')

# Every normal command still exits through SVP_PublishResultBody unchanged.
a.label('SVP_ChainResult')
a.st(RESULT)
a.lda(STAGE); a.tst(); a.br('SVP_ChainPublish', 'z')
a.cmpi(1); a.br('SVP_ChainRasterDone', 'z')
a.cmpi(2); a.br('SVP_ChainGeometryDone', 'z')
a.br('SVP_ChainEnd')

a.label('SVP_ChainRasterDone')
a.lda(RESULT); write(4)
a.cmpi('M4_RENDER_WORDS'); a.br('SVP_ChainFail', 'nz')
a.read_dram_i(8); a.clr(); a.pm_get(); write(5)  # cmd8 checksum, before cmd9 reuses RAM A
a.ldi(1); write(3)  # release old geometry, POLY_INPUT and bitmap to the host
a.label('SVP_ChainGeometry')
a.ldi(2); a.st(STAGE)
count(1); a.lda(SEQ); a.y_a(); a.br('SVP_Geometry')

a.label('SVP_ChainGeometryDone')
read(1); a.cmp(RESULT); a.br('SVP_ChainFail', 'nz')
a.ldi(3); a.st(STAGE)
count(2); a.tst(); a.br('SVP_ChainEmpty', 'z')
a.lda(SEQ); a.y_a(); a.br('SVP_Bsp')
a.label('SVP_ChainEmpty')
a.ldi(0); a.pmc_i(15); a.pmc_i(0x0018); a.pm_write_prog(); a.pm_put()
a.lda(SEQ); a.y_a(); a.br('SVP_Faces')

a.label('SVP_ChainFail')
a.ldi(0xffff); write(3)
a.label('SVP_ChainEnd')
a.ldi(0); a.st(STAGE)
a.label('SVP_ChainPublish')
a.lda(RESULT)
# Normal commands retain Y; the chain restores the same request tag.
a.br('SVP_PublishResultBody')

(ROOT / 'build/svp-chain.inc').write_text(
    '; Generated by tools/generate-svp-chain.py.\n' + '\n'.join(a.words_text()) + '\n', encoding='ascii')
print('Generated SVP13 chained raster/geometry/BSP/faces')
