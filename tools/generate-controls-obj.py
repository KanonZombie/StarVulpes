"""TRAINING/GAME box of the controls screen as Mega Drive sprites.

Source (selected USA rev0 ROM, build/research/screens-and-flow.md section 2):
contsprites 1F:FC61 writes 60 OAM 8x8 entries in a 10x6 grid from (168,151)
in 8-pixel steps, tile = table word + $3080 (tiles $80+n, priority 3, OBJ
palette 0, flips from the table); table selecttrain 1F:FCC6 (contexit 0) or
selectgame 1F:FD3E (contexit 1). OBJ characters obj2ccr (MDECRU, end
1F:B999, VRAM byte $D000 = OBJ tile $80), OBJ palette 0 = palette collection
7F:0540 (CGRAM $80).
MD: each variant is composed into a 80x48 image and cut into 6 sprites
(4x4, 4x4, 2x4 cells over two rows of 4 and 2 cells), tiles in VDP column
order; colours on CRAM line 3 (slots 1/2 already black/white). Screen
position: MD line = SNES line (plane B scrolled 1, OBJ y = OAM y + 1).
Output: build/screen-controls-obj.inc.
"""
from starfox_rom import rom_hex
import hashlib
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = runpy.run_path(str(ROOT / 'tools/convert-screen-bg.py'))
T = R['T']
rom = (ROOT / 'ref/Star Fox (USA).sfc').read_bytes()
assert hashlib.sha256(rom).hexdigest() == R['SHA']
decode = runpy.run_path(str(ROOT / 'tools/extract-intro-background.py'))['decode']
# contsprites code bytes (start position, steps, +$3080, tables)
code = rom[R['lorom'](0x1F, 0xFC61):R['lorom'](0x1F, 0xFCC6)]
for offset in (0xffc78, 0xffc89, 0xffcb1):
    assert bytes.fromhex(rom_hex(offset, 3)) in code
obj, obj_info = R['mdecru'](rom, decode, 0x1F, 0xB999)
col, _ = R['mdecru'](rom, decode, 0x17, 0xF21C)
pal = [col[0x540 + 2 * i] | col[0x541 + 2 * i] << 8 for i in range(16)]
tables = {}
for name, addr in (('Train', 0xFCC6), ('Game', 0xFD3E)):
    o = R['lorom'](0x1F, addr)
    tables[name] = [rom[o + 2 * i] | rom[o + 2 * i + 1] << 8 for i in range(60)]


def cell(word):
    tile = word & 0x1ff  # $80+n relative to the OBJ base: n = (word & $1ff)
    hf, vf = word & 0x4000, word & 0x8000
    out = []
    for y in range(8):
        sy = 7 - y if vf else y
        for x in range(8):
            sx = 7 - x if hf else x
            c = 0
            for p in range(4):
                byte = obj[tile * 32 + sy * 2 + (p & 1) + (p >> 1) * 16]
                c |= ((byte >> (7 - sx)) & 1) << p
            out.append(c)
    return out


slot = {0x000: 1, 0xeee: 2}
free = [s for s in range(3, 16)]
colours = []


def md_index(c):
    if not c:
        return 0
    v = T['md9'](pal[c])
    if v not in slot:
        slot[v] = free.pop(0)
        colours.append((slot[v], v, c))
    return slot[v]


out = ['; Generated by tools/generate-controls-obj.py (USA rev0 contsprites 1F:FC61, obj2ccr, 7F:0540).']
tiles = []
pieces = {}
sprites = {}
PIECES = [(0, 0, 4, 4), (4, 0, 4, 4), (8, 0, 2, 4), (0, 4, 4, 2), (4, 4, 4, 2), (8, 4, 2, 2)]
for name, words in tables.items():
    img = [[0] * 80 for _ in range(48)]
    for i, wd in enumerate(words):
        cx, cy = i % 10, i // 10
        px = cell(wd + 0x3080 - 0x3080)
        for y in range(8):
            for x in range(8):
                img[cy * 8 + y][cx * 8 + x] = md_index(px[y * 8 + x])
    entries = []
    for x0, y0, wc, hc in PIECES:
        piece = [[img[cy * 8 + y][cx * 8 + x] for y in range(8) for x in range(8)]
                 for cx in range(x0, x0 + wc) for cy in range(y0, y0 + hc)]  # VDP column order
        key = repr(piece)
        if key in pieces:  # equal piece of the other variant: shared tiles
            first = pieces[key]
        else:
            first = pieces[key] = len(tiles)
            tiles.extend(piece)
        size = ((wc - 1) << 2) | (hc - 1)
        entries.append((151 + 1 + y0 * 8, size, first, 168 + x0 * 8))
    sprites[name] = entries
out.append(f'M4_CTL_OBJ_TILES equ {len(tiles)}')
for name, entries in sprites.items():
    out.append(f'M4CtlBox{name}: ;y, size<<8, line 3 + tile, x (6 sprites)')
    for y, size, first, x in entries:
        out.append(f'        dc.w {y + 128},${size:02x}00,$e000|(M4_CTL_OBJ_VRAM/32+{first}),{x + 128}')
out.append('M4CtlObjColours: ;CRAM byte offset (line 3), MD colour')
for s, v, c in colours:
    out.append(f'        dc.w {96 + 2 * s},${v:03x} ;OBJ palette 0 colour {c}')
out.append('        dc.w -1')
out.append('M4CtlObjTiles:')
for t in tiles:
    b = T['tile_bytes'](t)
    out.append('        dc.l ' + ','.join(f'${int.from_bytes(b[i:i + 4], "big"):08x}' for i in range(0, 32, 4)))
# contmap 0D:FA3C (53 bytes, decoded in build/research/screens-and-flow.md 2.1)
cm = rom[R['lorom'](0x0D, 0xFA3C):R['lorom'](0x0D, 0xFA3C) + 53]
for start, end in ((0, 7), (31, 35), (35, 37), (37, 41), (41, 46), (47, 49), (49, 53)):
    assert cm[start:end].hex() == rom_hex(0x6fa3c + start, end - start), cm.hex()
assert cm[7] == 0x78 and cm[46] == 0x4e, cm.hex()
(ROOT / 'build/contmap.bin').write_bytes(cm)
(ROOT / 'build/screen-controls-obj.inc').write_text('\n'.join(out) + '\n', encoding='ascii')
print('controls OBJ:', len(tiles), 'tiles,', len(colours), 'new colours on line 3')
