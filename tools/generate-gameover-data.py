"""Game over screen data (gameover_l 02:E4C2, gameoverinit_l 06:BBDA).

Checks the ROM bytes the port transplants (selected USA rev0): the waiting map
0D:FA71 (wait and jump back), the GAME/OVER object
setup (shapes B235/B251, path istrat 04:8022, path $474D, HP $FF, AP 0,
x -270/+270, y +120, z +3400) and the 3D palette gameoverpal 02:F8B1 (row 7,
16 colours) converted to Mega Drive values (component >> 2).
Output: build/gameover-data.inc.
"""
from starfox_rom import rom_hex
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rom = (ROOT / 'ref/Star Fox (USA).sfc').read_bytes()
assert hashlib.sha256(rom).hexdigest() == '3857b5294ea8f7468849437bb2d8271564e8a0ff30774622e9c872bcbd53a84d'
phys = lambda b, a: b * 0x8000 + (a & 0x7fff)
script = rom[phys(0xD, 0xFA71):phys(0xD, 0xFA77)]
assert len(script) == 6
init = rom[phys(6, 0xBBDA):phys(6, 0xBD03)]
anchors = ((0x33c12, 3), (0x33c73, 3), (0x33c26, 3), (0x33c35, 3), (0x33c3d, 2),
           (0x33c4d, 3), (0x33cae, 3), (0x33c5b, 3), (0x33c69, 3), (0x33ce5, 4))
for offset, size in anchors:
    frag = rom_hex(offset, size)
    assert bytes.fromhex(frag) in init, frag
pal = rom[phys(2, 0xF8B1):phys(2, 0xF8B1) + 32]
md = []
for i in range(16):
    c = pal[2 * i] | pal[2 * i + 1] << 8
    r, g, b = c & 31, (c >> 5) & 31, (c >> 10) & 31
    md.append((r >> 2) << 1 | (g >> 2) << 5 | (b >> 2) << 9)
out = ['; Generated by tools/generate-gameover-data.py (USA rev0 02:F8B1, 0D:FA71, 06:BBDA).',
       'M4GoPalette: ;gameoverpal 02:F8B1 -> MD (line 2, GSU 3D colours)',
       '        dc.w ' + ','.join(f'${v:03x}' for v in md),
       'M4GoScriptBytes: ;0D:FA71',
       '        dc.b ' + ','.join(f'${value:02x}' for value in script),
       '        even']
(ROOT / 'build/gameover-data.inc').write_text('\n'.join(out) + '\n', encoding='ascii')
print('gameover data: palette sha', hashlib.sha256(pal).hexdigest()[:16])
