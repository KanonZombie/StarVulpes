"""Own SVP port of the route-map planets: GSU mdrawtsphere 01:B807 (cmd8 type 9) and the planet
sprites mdrawsprite32 01:CBF6 / musprite 01:CC59 (cmd8 type 10, models sprite32_model and
musprite_model of tools/route-planets-model.py).

Authority: ref/Star Fox (USA).sfc (rev0, SHA-256 below). Specification and reference model:
build/research/route-map-planets.md section 5 and tools/route-planets-model.py (sphere_model, equal
to the GSU bytes in 195/195 cases). This generator translates that model to SSP1601 code with the
same 16-bit wraps, truncations and order of writes:
  setup   light normalise (01:80C5 with the bit-serial sqrt 01:8086 and divide 01:8183, both
          translated literally), interpolated sine 00:99E5, matrix 01:829F + row normalise,
          reciprocal 00:9647 scaling (+1 when negative), light swap/scale;
  lines   xlen = msph_sqrt16 (equal to isqrt for every 16-bit input, checked below), mgenzlist
          (z search with the lo8 wrap that leaves z = -1), u/v/l per column (m_uvtab 01:BBF6 incl.
          the word after it, LMULT bits 8..23, hemisphere sign), mdrawuvlistx midpoints, LFSR
          $A63D dither and 15-tone shade, row y = yc-yp then yc+yp, right half then left half.
Port differences (deliberate, documented in build/agent-sphere/INTEGRATION.md):
  - colour: SNES index row*16+texel goes through a per-planet LUT to a 4-bit MD index (1..15);
  - output: packed VR tiles (as SVP_GridPlot/SVP_Sprite), written with masked overwrite PM mode
    $0418 (zero nibbles keep DRAM), bitmap position = atlas position + (dx, dy);
  - rows/columns outside the 256x192 bitmap are clipped or the record is rejected;
  - radius 1..62 (RAM1 z-list), light vector |v_i| <= 16383 (sum of squares < 2^31);
  - yp = 0 is drawn once (both GSU passes write identical pixels on the same row).
Outputs (only under build/agent-sphere/):
  svp-sphere.inc        SSP code + small program-space tables (include in the SVP program window)
  svp-sphere-rom.inc    SVP ROM data block (sine, reciprocals, uv, textures, LUTs), own page guard
  sphere-cram.inc       68000 CRAM lines for the LUTs (map lines A/B, zoom line per planet)
  svp-sphere.json       provenance, hashes, palettes, record contract
Usage: py -3.14 tools/generate-svp-sphere.py [--recompute-palette]
"""
import argparse
import hashlib
import importlib.util
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'build' / 'agent-sphere'
SHA = '3857b5294ea8f7468849437bb2d8271564e8a0ff30774622e9c872bcbd53a84d'


def load_model():
    spec = importlib.util.spec_from_file_location('route_planets_model', ROOT / 'tools' / 'route-planets-model.py')
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


M = load_model()
ROM_BYTES = (ROOT / 'ref' / 'Star Fox (USA).sfc').read_bytes()
assert hashlib.sha256(ROM_BYTES).hexdigest() == SHA, 'ROM hash'
TB = M.Tables(ROM_BYTES)

# Planet order of the port (texture id = LUT id for the map/zoom LUTs).
PLANETS = [(0, 'Corneria', 0x35), (4, 'Fortuna', 0x37), (5, 'Titania', 0x36), (11, 'Macbeth', 0x34),
           (15, 'Venom', 0x38)]
MAP_LINES = [[0, 1], [2, 3, 4]]          # measured best partition (route-map-planets.md 10.3)
LUT_DIAG_ROW, LUT_DIAG_TEX = 10, 11
MAX_RADIUS = 62                          # z-list: 4*(((r+1)>>1)+1) <= 128 RAM1 words

# =============================================================================================
# SSP emission helpers (same encodings as tools/generate-svp-sprites.py)
lines = ['; Generated by tools/generate-svp-sphere.py: own SVP port of GSU mdrawtsphere 01:B807',
         '; (route map planets, cmd8 type 9). Do not edit.']


def E(*words):
    lines.append('        dc.w ' + ','.join(f'${w & 65535:04x}' if isinstance(w, int) else w for w in words))


def L(name): lines.append(name + ':')
def load(s): E(0xe003, 0x0600 + s)          # A = ram[s]:0 (flags Z from eor)
def ldh(s): E(0x0600 + s)                    # A_hi = ram[s] (AL and flags kept)
def store(s): E(0x0e00 + s)
def imm(v): E(0xe003, 0x0830, v)
def add(s): E(0x8600 + s)
def sub(s): E(0x2600 + s)
def and_(s): E(0xa600 + s)
def or_(s): E(0xc600 + s)
def addi(v): E(0x8800, v)
def subi(v): E(0x2800, v)
def cmpi(v): E(0x6800, v)
def andi(v): E(0xa800, v)
def ori(v): E(0xc800, v)
def xori(v): E(0xe800, v)
def ldx(v): E(0x0810, v)
def ldy(v): E(0x0820, v)
def shl(n=1): E(*([0x9003] * n))
def sar(n=1): E(*([0x9002] * n))
def tst(s): E(0xe003, 0x8600 + s)            # A = ram[s]:0 with N/Z flags of the value
def call(name): E(0x4800, name + '/2')
def ret(): E(0x0065)
def br(name, cond='always'):
    E({'always': 0x4c00, 'z1': 0x4d50, 'z0': 0x4c50, 'n1': 0x4d70, 'n0': 0x4c70}[cond], name + '/2')


ABS, NEG_IF_N = 0x9007, 0x9176
LDXA, LDYA, LDAP, LDAX, LDA_AL, LDAL_A = 0x0013, 0x0023, 0x0037, 0x0031, 0x003f, 0x00f3
ADDP, SUBX = 0x8007, 0x2001
PROG_A = 0x4a30                              # A_hi = program word at A_hi
PROG_X = 0x4a10                              # X = program word at A_hi
PAGE = '$0800|((SVP_SphRom/2)>>16)'          # PM4 ROM read mode of the sphere block page


def rom(label):
    return f'(SVP_{label}/2)&$ffff'


def rom_setup():
    """A_hi = low word address in the sphere ROM page -> PM4 programmed for a ROM read."""
    E(0x00e3, 0x08e0, PAGE, 0x000c)


def fq(a, b, post=None, dst=None):
    """A_hi = fq(ram[a], ram[b]) = floor(a*b/2^15) (P = 2ab), optionally +/- ram[post]."""
    load(a); E(LDXA); load(b); E(LDYA, LDAP)
    if post:
        (add if post[0] == '+' else sub)(post[1])
    if dst is not None:
        store(dst)


# ---- RAM allocation: RAM1 only (cmd8 keeps its state in RAM0; RAM1 0x100..0x1cf is the
#      per-primitive scratch of SVP_Sprite/SVP_Radio*). Z-list: RAM1 0x100..0x17f (r4).
ZLIST = 0x100
_free = iter(range(0x180, 0x1d0))


def slots(n):
    return [next(_free) for _ in range(n)]


(XC, YC, DX, DY, RAD, TXL, SCALE, ROTX, ROTY, ROTZ, VX, VY, VZ, YTOP, YBOT) = slots(15)
(TEXB, LUTB, LUTB3, LUTEND, LUTM, YALO, YAHI, YBLO, YBHI, RSQ) = slots(10)
XS = slots(4); XSN = slots(4); YS = slots(4); ZS = slots(4); ACC = slots(4)
(YP, XLEN, R2B, R2, D, NZ, NCNT, Y, ROWADDR, RB, BX) = slots(11)
AQ = slots(4); Q = slots(4)
(V, U, LL, NV, NU, NL, AST, RND, ADDR, POSB, W, CNT, T, TI, TX) = slots(15)
# setup temporaries alias the z-list area (setup ends before the first z-list)
_tmp = iter(range(0x100, 0x180))
(SX, CX, SY, CY, SZ, CZ, R1, R2T, R13, R14, ANG, SA, RR, KL) = [next(_tmp) for _ in range(14)]
MAT = [next(_tmp) for _ in range(9)]
LSW = [next(_tmp) for _ in range(3)]
N = [next(_tmp) for _ in range(3)]
(SHI, SLO, R8, R6, R7, CNT16, K, DIVH, DIVL, DV, JT, T2) = [next(_tmp) for _ in range(12)]


def ptr(slot):
    return slot & 0xff


# =============================================================================================
# cmd8 type 9 record handler: rec0 in RAM0 0x40..0x47 (0x40 = 9), rec1 = next 8 DRAM words at
# ram0[1]; consumes it (ram0[1] += 8, ram0[2] -= 1) and draws.
L('SVP_SphereRecord')
load(2); cmpi(2); br('SVP_SphRet', 'n1')                   # continuation missing: ignore record
for i, s in enumerate((XC, YC, DX, DY, RAD, TXL, SCALE)):
    load(0x41 + i); store(s)
load(1); E(0x00e3, 0x08e0, 0x0818, 0x000c)                  # DRAM read, increment 1
for s in (ROTX, ROTY, ROTZ, VX, VY, VZ, YTOP, YBOT):
    E(0xe003, 0x003c); store(s)
load(1); addi(8); store(1)
load(2); subi(1); store(2)

# ---- core: inputs in the RAM1 slots above
L('SVP_Sphere')
lines.append('        if def(SVP_SPHERE_FAST)')
call('SVP_SphFastRadius'); cmpi(1)
lines.append('        else')
load(RAD); cmpi(1)
lines.append('        endif')
br('SVP_SphRet', 'n1'); cmpi(MAX_RADIUS + 1); br('SVP_SphRet', 'n0')
load(TXL); andi(0xff); cmpi(len(PLANETS)); br('SVP_SphRet', 'n0')
addi('SVP_SphTexTab/2'); E(PROG_A); store(TEXB)
load(TXL); E(LDXA); ldy(0x80); E(LDAP); andi(0xff)          # LUT id = high byte
lines.append('        if def(SVP_SPHERE_DIAG)')
cmpi(12)
lines.append('        else')
cmpi(10)
lines.append('        endif')
br('SVP_SphRet', 'n0')
addi('SVP_SphLutTab/2'); E(PROG_A); store(LUTB)
addi(1536); store(LUTB3); addi(512); store(LUTEND); subi(2560); store(LUTM)
# whole width inside the bitmap: 0 <= xc+dx-(r-1), xc+dx+(r-1) <= 255
load(XC); add(DX); sub(RAD); addi(1); br('SVP_SphRet', 'n1')
load(XC); add(DX); add(RAD); subi(257); br('SVP_SphRet', 'n0')
# rows: model window [ytop, ybot] (signed) intersected with the bitmap rows 0..191 - dy
imm(0); sub(DY); store(YBLO); sub(YTOP); br('SVP_SphYaTop', 'n1')     # YALO = max(ytop, -dy)
load(YBLO); store(YALO); br('SVP_SphYaDone')
L('SVP_SphYaTop'); load(YTOP); store(YALO)
L('SVP_SphYaDone')
imm(191); sub(DY); store(YAHI); sub(YBOT); br('SVP_SphYbBot', 'n1')   # YBHI = min(ybot, 191-dy)
load(YBOT); store(YBHI); br('SVP_SphYbDone')
L('SVP_SphYbBot'); load(YAHI); store(YBHI)
L('SVP_SphYbDone')

# ---- 5.1 light: n = normalise(lpos - bigpos); swap(sex(hi8(n))) = (n & $ff00) | (n<0 ? $ff : 0)
for s, d in zip((VX, VY, VZ), N):
    load(s); store(d)
call('SVP_SphNorm')
for i in range(3):
    load(N[i]); andi(0xff00); br(f'SVP_SphLsw{i}', 'n0'); ori(0xff)
    L(f'SVP_SphLsw{i}'); store(LSW[i])

# ---- 5.1.3 matrix mcrotmatzxy16 01:829F with interpolated sines
for ang, s, c in ((ROTX, SX, CX), (ROTY, SY, CY), (ROTZ, SZ, CZ)):
    load(ang); store(ANG); call('SVP_SphSinSub'); store(s)
    load(ang); addi(0x4000); store(ANG); call('SVP_SphSinSub'); store(c)
fq(SY, CZ, dst=R1); fq(CY, CZ, dst=R2T); fq(SY, SZ, dst=R13); fq(CY, SZ, dst=R14)
fq(R13, SX, ('+', R2T), MAT[0]); fq(R1, SX, ('-', R14), MAT[1]); fq(SY, CX, dst=MAT[2])
fq(SZ, CX, dst=MAT[3]); fq(CZ, CX, dst=MAT[4]); imm(0); sub(SX); store(MAT[5])
fq(R14, SX, ('-', R1), MAT[6]); fq(R2T, SX, ('+', R13), MAT[7]); fq(CY, CX, dst=MAT[8])
for row in range(3):
    for i in range(3):
        load(MAT[3 * row + i]); store(N[i])
    call('SVP_SphNorm')
    for i in range(3):
        load(N[i]); store(MAT[3 * row + i])

# ---- 5.1.4 scale by the radius: rr = reciptab[r]; S = fq(M, rr) (+1 if negative)
lines.append('        if def(SVP_SPHERE_FAST)')
call('SVP_SphFastRecip'); E(*([0]*9))
lines.append('        else')
load(RAD); addi(rom('SphRecip')); rom_setup(); E(0xe003, 0x003c); store(RR)
lines.append('        endif')
for i in range(9):
    fq(MAT[i], RR); cmpi(0); br(f'SVP_SphSPos{i}', 'n0'); addi(1)
    L(f'SVP_SphSPos{i}'); store(MAT[i])                      # S overwrites M
fq(SCALE, RR, dst=KL)
for i in range(3):
    fq(LSW[i], KL, dst=LSW[i])                              # light_i
S11, S12, S13, S21, S22, S23, S31, S32, S33 = MAT
L1, L2, L3 = LSW
for dst, src in zip(XS, (S21, S11, S31, L1)):              # x steps doubled (columns of 2 px)
    load(src); shl(); store(dst)
for dst, src in zip(XSN, XS):
    imm(0); sub(src); store(dst)
for dst, src in zip(YS, (S22, S12, S32, L2)):
    load(src); store(dst)
for dst, src in zip(ZS, (S23, S13, S33, L3)):
    load(src); store(dst)

# ---- 5.2 lines
imm(0); store(YP)
for a in ACC:
    store(a)
lines.append('        if def(SVP_SPHERE_FAST)')
load(RAD); store(XLEN); load(0x1d1); store(RSQ); E(0,0,0)
lines.append('        else')
load(RAD); store(XLEN); E(LDXA, LDYA, LDAP); sar(); E(LDA_AL); store(RSQ)
lines.append('        endif')
L('SVP_SphLine')
load(YP); addi('SVP_SphSq/2'); E(PROG_A); store(T); load(RSQ); sub(T); store(R2B)
L('SVP_SphXlen')                                            # xlen = isqrt(r^2 - yp^2), decreasing
load(XLEN); addi('SVP_SphSq/2'); E(PROG_A); sub(R2B)
br('SVP_SphXlenOk', 'n1'); br('SVP_SphXlenOk', 'z1')
load(XLEN); subi(1); store(XLEN); br('SVP_SphXlen')
L('SVP_SphXlenOk')
# mgenzlist 01:B9C2: n = ((xlen+1)>>1)+1 entries (S23 z, S13 z, S33 z, L3 z) low words
load(XLEN); store(NZ); load(R2B); store(R2); imm(12); store(D)
load(XLEN); addi(1); sar(); andi(0x7fff); addi(1); store(NCNT)
E(0x1c00 | ptr(ZLIST))
L('SVP_SphZ')
load(NZ); E(LDYA, 0x1d00 | ptr(ZS[0]))
for _ in range(4):
    E(0x0315, LDAP, 0x9002, LDA_AL, 0x0534)                   # X=(r5)+; lo16(S*z) -> (r4)+
load(R2); sub(D); store(R2); load(D); addi(8); store(D)
L('SVP_SphZs')
load(NZ); andi(0xff); addi('SVP_SphSq/2'); E(PROG_X); load(R2); E(SUBX); br('SVP_SphZd', 'n0')
load(NZ); subi(1); store(NZ); br('SVP_SphZs')
L('SVP_SphZd')
load(NCNT); subi(1); store(NCNT); br('SVP_SphZ', 'z0')
# line yc - yp (accumulators negated), then yc + yp; yp = 0 drawn once (identical pixels)
load(YC); sub(YP); store(Y)
load(Y); sub(YALO); br('SVP_SphSkipA', 'n1'); load(YAHI); sub(Y); br('SVP_SphSkipA', 'n1')
tst(YP); br('SVP_SphDrawA', 'z0')
load(Y); sub(YBLO); br('SVP_SphDrawA', 'n1'); load(YBHI); sub(Y); br('SVP_SphDrawA', 'n1')
br('SVP_SphSkipA')
L('SVP_SphDrawA')
for a, q in zip(ACC, AQ):
    imm(0); sub(a); store(q)
call('SVP_SphDrawLine')
L('SVP_SphSkipA')
load(YC); add(YP); store(Y)
load(Y); sub(YBLO); br('SVP_SphSkipB', 'n1'); load(YBHI); sub(Y); br('SVP_SphSkipB', 'n1')
for a, q in zip(ACC, AQ):
    load(a); store(q)
call('SVP_SphDrawLine')
L('SVP_SphSkipB')
for a, s in zip(ACC, YS):
    load(a); add(s); store(a)
load(YP); addi(1); store(YP); sub(RAD); br('SVP_SphLine', 'z0')
L('SVP_SphRet')
ret()

# =============================================================================================
# One row: ROWADDR, dither seed, right half (x = xc..), left half (x = xc..xc-xl+1).
L('SVP_SphDrawLine')
load(Y); add(DY); store(T)                                   # bitmap row 0..191
andi(0xfff0); shl(6); store(ROWADDR)
load(T); andi(15); shl(); add(ROWADDR); add(0xf6); store(ROWADDR)   # + framebuffer base (RAM0 F6)
# rnd seed (01:BB18): r0 = s8(lo8(4y))*13 + y ; seed = swap(r0) + x
load(Y); shl(2); andi(0xff); xori(0x80); subi(0x80); E(LDXA); ldy(13); E(LDAP); sar(); E(LDA_AL)
add(Y); E(LDXA); ldy(0x80); E(LDAP); store(T); E(LDA_AL); store(TX)
load(T); andi(0xff); or_(TX); store(RB)
for side in ('R', 'L'):
    right = side == 'R'
    load(XC); add(DX); store(BX)
    andi(0xfff8); shl(2); add(ROWADDR); store(ADDR)
    load(BX); andi(4); br(f'SVP_SphAst{side}', 'z1')
    sar(2); add(ADDR); store(ADDR); imm(31 if right else 1); br(f'SVP_SphAstSet{side}')
    L(f'SVP_SphAst{side}'); imm(1 if right else 31)
    L(f'SVP_SphAstSet{side}'); store(AST)                   # WORD step: right +1/+31, left -31/-1
    load(BX); andi(3); shl(9); add(LUTB); store(POSB)
    imm(0); store(W)
    load(XLEN); sar(); andi(0x7fff); store(CNT)              # pixel pairs; xlen odd: one more A
    load(RB); add(XC)
    if not right:
        addi(0x8000)
    store(RND)
    for q, a in zip(Q, AQ):
        load(a); store(q)
    E(0x1c00 | ptr(ZLIST), 0x1d00 | ptr(LL))                 # r4: z-list, r5: light of the pixel
    steps = XS if right else XSN

    def entry(dv, du, dl):
        """mgenuvlistx 01:BA9A for the next z-list entry; q += c afterwards."""
        E(0xe003, 0x0334); add(Q[0]); store(T)               # r4 = z*S23 + q1 (AL = 0)
        E(ABS, LDXA); ldy(0x0800); E(LDAP); andi(0x0fff)       # |r4| >> 4 ($8000 -> $800)
        lines.append('        if def(SVP_SPHERE_FAST)')
        addi('SVP_SphFastUV/2'); E(PROG_X)                   # direct program-space read
        lines.append('        else')
        addi(rom('SphUV')); rom_setup(); E(0x001c)           # X = 2*uv
        lines.append('        endif')
        E(0x0334); add(Q[1]); E(LDYA, LDAP); shl(6); sar(); addi(0x4000); store(du)   # asr(bits 8..23 of uv*E)
        E(0xe003, 0x0334); add(Q[2]); ldh(du); E(NEG_IF_N); store(du)   # back hemisphere: w1 = -w1
        E(0x0334); add(Q[3]); store(dl)
        load(T); sar(); addi(0x4000); store(dv)
        for q, c in zip(Q, steps):
            ldh(q); add(c); store(q)

    def pixel(vsum, tag):
        """01:BB18..BB8E: texel, LFSR, shade row, LUT, packed nibble, masked word write.
        vsum: pixel A uses v = (V+NV)>>1 (only its bits 10..14 = bits 11..15 of V+NV are read)."""
        if vsum:
            ldh(V); add(NV); E(LDXA); ldy(0x0400)
        else:
            ldh(V); E(LDXA); ldy(0x0800)
        E(LDAP); andi(0x07c0); store(TI)                       # texture row * 64
        ldh(U); E(LDXA); ldy(0x20); E(LDAP); andi(0x003f); add(TI); add(TEXB)
        lines.append('        if def(SVP_SPHERE_FAST)')
        E(PROG_A); store(TX)                               # same texels, no PM4 reprogramming
        lines.append('        else')
        rom_setup(); E(0x003c); store(TX)
        lines.append('        endif')
        E(0xe003); add(RND); br(f'SVP_SphNc{tag}', 'n0'); shl(); xori(0xa63d); br(f'SVP_SphRn{tag}')
        L(f'SVP_SphNc{tag}'); shl()
        L(f'SVP_SphRn{tag}'); store(RND)
        # (8*lo8(rnd) + l) * 512 = lo8*4096 + l*512; bits 11..15 of the 16-bit sum -> hb*16
        andi(0xff); E(LDXA); ldy(0x0800); E(LDAP, 0x0311); ldy(0x0100); E(ADDP); andi(0x01f0)
        add(TX); add(POSB); rom_setup(); E(0x003c); or_(W); store(W)
        ldh(POSB)                                             # AL = 0 here
        if right:
            addi(512); store(POSB); sub(LUTEND)
        else:
            subi(512); store(POSB); sub(LUTM)
        br(f'SVP_SphPn{tag}', 'z0')
        # word complete: masked overwrite (mode $0418, zero nibbles keep DRAM), next WORD
        ldh(ADDR); E(0x00e3, 0x08e0, 0x0418, 0x00c0); ldh(W); E(0x00c3)
        imm(0); store(W); ldh(LUTB if right else LUTB3); store(POSB)
        ldh(ADDR); (add if right else sub)(AST); store(ADDR); imm(32); sub(AST); store(AST)
        L(f'SVP_SphPn{tag}')

    def pixel_a(tag):
        pixel(True, tag)
        ldh(U); sub(NU); sar(); add(NU); store(U)            # u = nu + asr(u - nu)
        ldh(LL); sub(NL); sar(); add(NL); store(LL)          # l = nl + asr(l - nl)
        ldh(NV); store(V)

    entry(V, U, LL)
    tst(CNT); br(f'SVP_SphOdd{side}', 'z1')
    L(f'SVP_SphLoop{side}')
    entry(NV, NU, NL)
    pixel_a(side + 'A')
    pixel(False, side + 'B')
    ldh(CNT); subi(1); store(CNT); br(f'SVP_SphLoop{side}', 'z0')
    L(f'SVP_SphOdd{side}')
    load(XLEN); andi(1); br(f'SVP_SphEnd{side}', 'z1')
    entry(NV, NU, NL)
    pixel(True, side + 'O')
    L(f'SVP_SphEnd{side}')
    tst(W); br(f'SVP_SphNoTail{side}', 'z1')
