def shade_row(hb):
    return 14 if hb == 0 or hb >= 16 else 15 - hb


def histograms():
    st = M.MapState(TB)
    circle = {}
    for a in (0, 64, 128, 192):
        s = M.MapState(TB)
        s.lightangle = a << 8
        M.irq_light_step(TB, s)
        circle[a] = [M.s16(s.lightx), M.s16(s.lighty)]
    lights = [circle[a] + [200] for a in (0, 64, 128, 192)] + [[60, 200, 200]]
    out = {}
    for pi, (k, name, tid) in enumerate(PLANETS):
        h = {}
        for li, (lx, ly, lz) in enumerate(lights):
            for i in range(0, 256, 16):
                st.roty = [i << 8] * 6
                st.lpos = [lx & 0xFFFF, ly & 0xFFFF, lz]
                for radius, xc, yc in ((15, 16 + 32 * (k % 4), 16 + 32 * (k // 4)), (54, 64, 64)):
                    if radius == 54 and (i % 64 or li % 2):
                        continue
                    for x, y, c in M.sphere_model(TB, M.sphere_params(TB, st, k, xc, yc, radius)):
                        h[c] = h.get(c, 0) + 1
        out[name] = {str(c): w for c, w in sorted(h.items())}
    return dict(lights=lights, hist=out)


def palette_for(hist_by_index, n=15):
    rgbh = {}
    for c, w in hist_by_index.items():
        rgb = M.bgr555(TB, int(c))
        rgbh[rgb] = rgbh.get(rgb, 0) + w
    pal = M.kmeans(rgbh, n)
    return pal, M.quant_error(rgbh, pal)


# MD index slots of each LUT family (port integration, routemap.asm): map line
# A = CRAM line 2 (slots 1..15); map line B = CRAM line 3, whose colour 1 is
# the black of the plane A margin tiles (slots 2..15); zoom = CRAM line 2 with
# Pepper's text colours in slots 1, 4, 5, 13 (11 planet slots).
SLOTS_ALL = list(range(1, 16))
SLOTS_LINE3 = list(range(2, 16))
SLOTS_ZOOM = [2, 3, 6, 7, 8, 9, 10, 11, 12, 14, 15]


def lut_for(pal, slots=SLOTS_ALL):
    out = []
    for c in range(256):
        rgb = M.bgr555(TB, c)
        out.append(slots[min(range(len(pal)), key=lambda i: (M.dist(rgb, pal[i]), i))])
    return out


def cram_line(pal, slots):
    line = [0] * 16
    for c, sl in zip(pal, slots):
        line[sl] = cram(c)
    return line


def cram(rgb):
    n = [min(7, max(0, round(v * 7 / 255))) for v in rgb]
    return (n[2] << 9) | (n[1] << 5) | (n[0] << 1)


def colour_tables(recompute=False):
    """LUTs 0..11 (SNES row*16+texel -> MD index), CRAM lines, palette report, histograms."""
    OUT.mkdir(parents=True, exist_ok=True)
    cache = OUT / 'sphere-histograms.json'
    if recompute or not cache.exists():
        hist = histograms()
        hist['rom_sha256'] = SHA
        cache.write_text(json.dumps(hist, indent=1) + '\n')
    hist = json.loads(cache.read_text())
    assert hist['rom_sha256'] == SHA
    luts, pal_report, cram_lines = [], {}, {}
    names = [p[1] for p in PLANETS]
    map_pal = []
    for li, members in enumerate(MAP_LINES):
        h = {}
        for m in members:
            for c, w in hist['hist'][names[m]].items():
                h[c] = h.get(c, 0) + w
        slots = SLOTS_LINE3 if li == 1 else SLOTS_ALL
        pal, err = palette_for(h, len(slots))
        map_pal.append((pal, slots))
        cram_lines[f'M4SphereCramMap{li}'] = cram_line(pal, slots)
        pal_report[f'map_line_{li}'] = dict(planets=[names[m] for m in members], error=err,
                                            colours=['%02X%02X%02X' % c for c in pal])
    for pi in range(len(PLANETS)):
        line = next(li for li, mem in enumerate(MAP_LINES) if pi in mem)
        luts.append(lut_for(*map_pal[line]))
    for pi, name in enumerate(names):
        pal, err = palette_for(hist['hist'][name], len(SLOTS_ZOOM))
        cram_lines[f'M4SphereCramZoom{pi}'] = cram_line(pal, SLOTS_ZOOM)
        pal_report[f'zoom_{name}'] = dict(error=err, colours=['%02X%02X%02X' % c for c in pal])
        luts.append(lut_for(pal, SLOTS_ZOOM))
    luts.append([(c >> 4) + 1 for c in range(256)])          # diag: shade row + 1
    luts.append([c & 15 for c in range(256)])                # diag: texel
    for lut in luts[:10]:
        assert all(1 <= v <= 15 for v in lut)

    return luts, pal_report, cram_lines, hist


