"""GSU screen texts of the game loop (PAUSED, results) as port data.

Source (selected USA rev0 ROM): the mprintstr strings 01:E796..E81F (colour
byte, ASCII, 0; build/research/screens-and-flow.md section 6.1, SHA-256 of the
138 bytes 8c16dda7...) and the results tables of end_level_seq 02:EC20
(nametxt 02:EBA3, namepos 02:EBA9, deadnamepos 02:EBAF, namegfxpos 02:EBB5;
build/research/corneria-missing.md section 4.6). Faces of mcopyface 01:D15B
are entries of the radio face table 17:B9C0 (640 bytes each).
Output: build/level-texts.inc and build/level-result-faces.inc.
"""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rom = (ROOT / 'ref/Star Fox (USA).sfc').read_bytes()
assert hashlib.sha256(rom).hexdigest() == '3857b5294ea8f7468849437bb2d8271564e8a0ff30774622e9c872bcbd53a84d'
phys = lambda bank, addr: bank * 0x8000 + (addr & 0x7fff)
w = lambda o: rom[o] | rom[o + 1] << 8
start = phys(1, 0xE796); end = start + 138
assert hashlib.sha256(rom[start:end]).hexdigest().startswith("8c16dda7")

strings, o = {}, start
while o < end:
    z = rom.index(0, o)
    strings[0x8000 + (o & 0x7fff)] = rom[o:z + 1]
    o = z + 1
names = {0xE796: 'Paused', 0xE79E: 'TotalScore', 0xE7AB: 'Score', 0xE7C1: 'Bonus', 0xE7D1: 'Percent',
         0xE7DF: 'Shield', 0xE7F4: 'Slippy', 0xE7FC: 'Peppy', 0xE803: 'Falco', 0xE80A: 'IsDown'}
out = ['; Generated by tools/generate-level-texts.py (USA rev0 01:E796..E81F, 02:EBA3..EBBA).']
for addr, label in names.items():
    s = strings[addr]
    assert s[0] == 0x0e and s[-1] == 0, (hex(addr), s)
    out.append(f'M4GsuStr{label}: ;01:{addr:04X} "{s[1:-1].decode()}"')
    out.append('        dc.b ' + ','.join(f'${b:02x}' for b in s))
out.append('        even')
# end_level_seq tables, order Peppy ($18A2), Falco ($18A3), Slippy ($18A4)
nametxt = [w(phys(2, 0xEBA3) + 2 * i) for i in range(3)]
assert len(set(nametxt)) == 3 and all(addr in names for addr in nametxt)
namepos = list(rom[phys(2, 0xEBA9):phys(2, 0xEBA9) + 6])
deadpos = list(rom[phys(2, 0xEBAF):phys(2, 0xEBAF) + 6])
gfxpos = list(rom[phys(2, 0xEBB5):phys(2, 0xEBB5) + 6])
out.append('M4ResNames: ;nametxt 02:EBA3')
out.append('        dc.l ' + ','.join(f'M4GsuStr{names[addr]}' for addr in nametxt))
out.append(f'M4ResNamePos: ;namepos 02:EBA9 {namepos}')
out.append('        dc.w ' + ','.join(str(w2) for w2 in (namepos[0] | namepos[1] << 8, namepos[2] | namepos[3] << 8, namepos[4] | namepos[5] << 8)))
out.append(f'M4ResDeadPos: ;deadnamepos 02:EBAF {deadpos}')
out.append('        dc.w ' + ','.join(str(w2) for w2 in (deadpos[0] | deadpos[1] << 8, deadpos[2] | deadpos[3] << 8, deadpos[4] | deadpos[5] << 8)))
out.append(f'M4ResFacePos: ;namegfxpos 02:EBB5 {gfxpos} (x in 8-pixel units, y)')
out.append('        dc.b ' + ','.join(map(str, gfxpos)))
(ROOT / 'build/level-texts.inc').write_text('\n'.join(out) + '\n', encoding='ascii')


def face_frame(address):
    offset = phys(2, address)
    assert rom[offset] == 0xa9  # LDA immediate, M=16.
    index, remainder = divmod(w(offset + 1) - 0xb9c0, 640)
    assert remainder == 0 and 0 <= index < 18
    return index


faces = ['; Generated by tools/generate-level-texts.py from 02:EED6..EEF8.',
         f'M4ResDeadFrameEven equ {face_frame(0xeed6)}',
         f'M4ResDeadFrameOdd equ {face_frame(0xeedb)}',
         '        dc.b ' + ','.join(str(face_frame(addr)) for addr in (0xeef1, 0xeef6, 0xeeec))]
(ROOT / 'build/level-result-faces.inc').write_text('\n'.join(faces) + '\n', encoding='ascii')
print('Generated level texts:', len(names), 'strings; namepos', namepos, 'deadpos', deadpos, 'gfxpos', gfxpos)
