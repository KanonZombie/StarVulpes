"""Path bytecode of the selected ROM for the 68000 path interpreter.

Source: build/research/corneria-paths.md (interpreter 04:805F, table 04:807C,
166 opcodes, names from tools/path-oracle.py). The path area starts at
04:A3FE (lda.l $04A3FE,x at 04:8063); Corneria 1 uses offsets 0000..45B5
(28 paths decoded by tools/path-oracle.py). Outputs:
  build/level-paths.bin  path bytes (offset 0 = 04:A3FE)
  build/level-paths.inc  M4_PATH_SIZE and M4PathOps (166 handler pointers;
                         opcodes without a ported handler -> M4PvBadOp; since
                         the build/agent-paths batch every opcode has one)
"""
from starfox_rom import rom_hex
import hashlib
import re
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rom = (ROOT / 'ref/Star Fox (USA).sfc').read_bytes()
assert hashlib.sha256(rom).hexdigest() == '3857b5294ea8f7468849437bb2d8271564e8a0ff30774622e9c872bcbd53a84d'
oracle = runpy.run_path(str(ROOT / 'tools/path-oracle.py'), run_name='path_oracle')
NAMES = oracle['NAMES']
assert len(NAMES) == 166
START, SIZE = 0x04 * 0x8000 + (0xA3FE & 0x7FFF), 0x8000 - (0xA3FE & 0x7FFF)  # the whole path area to 04:FFFF (all stages)
assert START == 0x223FE and START + SIZE <= 0x28000
# The interpreter fetch (04:8063) and the dispatcher table base (04:807C).
assert rom[0x20063:0x20067].hex() == rom_hex(0x20063, 4), rom[0x20063:0x20067].hex()
data = rom[START:START + SIZE]
(ROOT / 'build/level-paths.bin').write_bytes(data)
source = (ROOT / 'src/level/level_paths.asm').read_text(encoding='ascii')
ported = set(re.findall(r'^M4PvOp_(\w+):', source, re.M))
unknown = ported - set(NAMES)
assert not unknown, unknown
lines = ['; Generated by tools/extract-level-paths.py from the selected USA rev0 ROM.',
         f'M4_PATH_SIZE equ ${SIZE:04x} ;path bytes 04:A3FE.., sha256 {hashlib.sha256(data).hexdigest()[:16]}',
         'M4_PATH_OPS equ 166', 'M4PathOps:']
for op, name in enumerate(NAMES):
    label = f'M4PvOp_{name}' if name in ported else 'M4PvBadOp'
    lines.append(f'        dc.l {label} ;{op:02X} {name}')
(ROOT / 'build/level-paths.inc').write_text('\n'.join(lines) + '\n', encoding='ascii')
print(f'Extracted {SIZE} path bytes; {len(ported)} of 166 opcodes ported')
